// license_store.hpp — де на носії лежить підпис ліцензії.
//
// Не окремий файл "license.key" з очевидною назвою, а 64 байти на
// фіксованому зміщенні всередині файлу-приманки, повного випадкових
// байтів. Підпис Ed25519 статистично не відрізняється від шуму навколо,
// тож просто переглядом файлу його не знайти й не відрізнити від решти.
//
// Це ОБФУСКАЦІЯ, а не сам захист: той, хто розбере бінарник, побачить і
// шлях, і зміщення. Захист дає підпис — зміщення лише вповільнює пошук
// місця, куди дивитися. Тому криптографію (ed25519) ховати немає сенсу, а
// це — має.
#pragma once

#include <cstdint>
#include <string>

namespace vrx::license {

// Зміщення 64-байтового підпису у файлі-приманці. Те саме число прошите
// в tools/vrx_activate.sh — якщо міняєш тут, зміни і там.
constexpr long kSignatureOffset = 11024;   // 0x2B10
constexpr int  kSignatureLen = 64;

// Читає 64 байти підпису зі сховку. false, якщо файлу немає або він
// закороткий (тоді ліцензія вважається відсутньою -> ворота не пустять).
bool read_signature(const std::string& store_path, uint8_t out_sig[64]);

} // namespace vrx::license
