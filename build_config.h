//
// Кожен перемикач вимикається НА КОМПІЛЯЦІЇ, а не прапорцем у рантаймі, і
// це не педантизм. Діагностика тут сидить у гарячих місцях — у колбеку
// appsink, в обробнику розгортки, у циклі рекордера. Прапорець лишив би
// там перевірку назавжди, а головне — лишив би сам код у бойовому
// бінарнику. З дефайном у вимкненому стані від точок виміру не лишається
// нічого: порожні макроси.
//
// Перемикачі РІЗНІ навмисно. Вони вмикаються в різних ситуаціях і мають
// різну ціну: вимір тракту жере пам'ять і пише мегабайти сирих рядів,
// детальний лог запису — ні. Зводити їх в один "DEBUG" означало б платити
// за все одразу щоразу, коли треба одне.
//
// ЯК УВІМКНУТИ. Або правкою нуля на одиницю тут (тоді перезбирати треба
// все, що цей заголовок включає), або з командного рядка, не чіпаючи
// файл:
//
//     cmake -B build-measure -DCMAKE_CXX_FLAGS=-DVRX_MEASURE=1
//     cmake -B build-rec     -DCMAKE_CXX_FLAGS=-DVRX_RECORD_LOG=1
//     cmake -B build-both    -DCMAKE_CXX_FLAGS="-DVRX_MEASURE=1 -DVRX_RECORD_LOG=1"
//
// Окремий каталог збірки на кожен набір — щоб бойовий бінарник лишався
// поруч і не доводилось перезбирати його назад.

