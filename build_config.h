#endif

// ДЕТАЛЬНИЙ ЛОГ ЗАПИСУ: кожне рішення рекордера й кожен крок носія з
// мітками часу — коли відкрився й закрився файл і ЧОМУ, скільки тривало
// закриття, скільки тривала кожна перевірка носія, скільки тривав syncfs
// і скільки при цьому лишалось незаписаного в ядрі.
//
// Навіщо окремо від штатного логу. Штатний друкує стан раз на дві
// секунди — цього досить, щоб бачити, що все гаразд, і замало, щоб
// розібрати збій: подія триває мілісекунди, а між знімками дві секунди.
// А головне — при зриві носія цікавий саме ПОРЯДОК подій, якого зведення
// не зберігає в принципі.
//
// Ціна: один рядок на подію плюс биття раз на секунду. Пише у файл із
