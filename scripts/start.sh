#!/usr/bin/env bash
# Запуск VRX-GL. Викликається ярликом з робочого столу через sudo.
#
# Потребує root: DRM master ексклюзивний, без нього не буде ні зміни
# режиму, ні плейна.
set -euo pipefail

# Корінь проєкту рахується від РОЗТАШУВАННЯ САМОГО СКРИПТА, а не
# прибитий у тексті. Саме через це папку можна просто розпакувати
# будь-куди й під будь-яким користувачем — нічого правити не треба.
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="$HERE/build/vrx_gl"
LOGDIR="$HERE/logs"

if [[ ! -x "$BIN" ]]; then
  echo "Не знайдено збірку: $BIN" >&2
  echo "Спершу виконайте scripts/install.sh" >&2
  exit 1
fi

mkdir -p "$LOGDIR"
LOG="$LOGDIR/vrx-gl_$(date +%Y%m%d_%H%M%S).log"

# Лишаємо останні 10 логів: на польотах їх набігає багато, а місце на
# оранжі не безмежне.
#
# "|| true" тут обов'язковий. При set -o pipefail порожній ls (логів ще
# немає — а так і буде на новій машині) робить помилкою весь конвеєр, і
# set -e виходить зі скрипта ДО запуску. Тобто без цього ярлик не
# спрацював би саме там, де має спрацювати вперше.
ls -1t "$LOGDIR"/vrx-gl_*.log 2>/dev/null | tail -n +11 | xargs -r rm -f || true

# Друга копія не піднімається: DRM master ексклюзивний, і вона просто
# впаде з незрозумілою помилкою. Гасимо стару мовчки.
if pgrep -x vrx_gl >/dev/null 2>&1; then
  echo "Зупиняю попередню копію..."
  pkill -x vrx_gl || true
  for _ in $(seq 1 30); do
    pgrep -x vrx_gl >/dev/null 2>&1 || break
    sleep 0.2
  done
fi

# РОБОЧИЙ КАТАЛОГ — корінь проєкту, і це не косметика: атлас OSD,
# osd_config.json і картинки шукаються за відносними шляхами. Запуск із
# іншого каталогу дасть відео без OSD і незрозумілу помилку в лозі.
cd "$HERE"

echo "VRX-GL: $BIN"
echo "Лог:    $LOG"
exec "$BIN" "$@" >>"$LOG" 2>&1
