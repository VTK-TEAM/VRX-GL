#pragma once

// ЧОРНА СКРИНЬКА BETAFLIGHT ПО ETHERNET.
//
// Борт шле лог у НЕЗМІННОМУ форматі .bbl шматками по ≤247 байтів. Станція
// лише складає шматки у файл — жодного розбору вмісту. Файл відкривається
// Blackbox Explorer як є, так само, ніби його писали на мікроSD.
//
// Труба 102, порт 50124, кадр той самий, що й у телеметрії:
//   [pipe_id][length][payload][crc8],  crc від pipe_id+payload без length.
//
// Payload: [seq: u16 LE][flags: u8][data: 0…247 Б]
//   flags біт0 — початок логу, біт1 — кінець (може прийти без даних).
//
// ДВА ПОТОКИ, І ЦЕ ВИМОГА, А НЕ СМАК. Потік запису на флешці зависає на
// сотні мілісекунд; якби прийом чекав на нього, приймальний буфер сокета
// переповнився б, і кадри губились би мовчки. Тому прийом складає в чергу,
// а запис розбирає її своїм темпом.
//
// ДІРИ МАЮТЬ БУТИ ВИДНІ. Розрив seq означає втрачені кадри; писати далі
// треба (Explorer ресинхронізується на найближчому опорному кадрі), але
// тихо зшивати не можна — інакше лог виглядає цілим, а він не цілий.

#include <cstdint>
#include <memory>

namespace vrx::record {

class Storage;

class Blackbox {
public:
    struct Config {
        int port = 50124;

        // Писати великими блоками: флешка не любить дрібних записів.
        // Специфікація радить від 64 КБ, беремо з запасом.
        size_t block_bytes = 256u * 1024;

        // Приймальний буфер сокета. При 40 КБ/с і затику запису на пів
        // секунди тут має вміститись усе, що прилетить за той час.
        int rcvbuf_bytes = 4 * 1024 * 1024;

        // Межа черги між прийомом і записом. Переповнилась — кадри
        // ВИКИДАЮТЬСЯ і рахуються. Краще втратити хвіст і знати про це,
        // ніж з'їсти пам'ять і впасти.
        size_t queue_max_bytes = 16u * 1024 * 1024;

        // Тиша після даних без "кінця логу" — зник лінк, зняли живлення.
        // Обрізаний .bbl валідний, Explorer його відкриває.
        int idle_close_ms = 5000;
    };

    struct Stats {
        uint64_t frames = 0;      // прийнято кадрів
        uint64_t bytes = 0;       // записано байтів даних
        uint64_t gaps = 0;        // розривів seq
        uint64_t lost = 0;        // кадрів, загублених у розривах
        uint64_t dropped = 0;     // викинуто через переповнення черги
        uint64_t bad = 0;         // бракованих кадрів (CRC, довжина, чужа труба)
        uint64_t files = 0;       // відкрито файлів
        bool open = false;        // файл відкритий зараз
    };

    Blackbox(Config cfg, Storage& storage);
    ~Blackbox();

    Blackbox(const Blackbox&) = delete;
    Blackbox& operator=(const Blackbox&) = delete;

    bool start();
    void stop();
    Stats stats() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::record
