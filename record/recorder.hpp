#pragma once

// Запис одного відеопотоку. Один екземпляр на кожен потік, власний
// системний потік, власний пайплайн зі своїм udpsrc.
//
// ПОВНА НЕЗАЛЕЖНІСТЬ ВІД ПОКАЗУ. Спільного з трактом показу немає
// нічого: ні елемента, ні буфера, ні сокета. Борт шле бродкастом, а
// ядро віддає копію кожної датаграми КОЖНОМУ сокету на порту —
// перевірено, юнікаст натомість балансується між сокетами й для цього
// не годиться. Тому запис фізично не має шляху вплинути на показ: що б
// тут не зламалось, включно з висмикнутою посеред кадру флешкою,
// картинка на екрані цього не помітить.
//
// У старому VRX запис висів на тій самій гілці tee, що й показ, і зрив
// носія вішав увесь тракт до спрацювання вачдога. Саме тому тут окремий
// пайплайн, а не спільний.
//
// НЕ ДЕКОДУЄМО. Пишеться стиснений потік як є. Це не оптимізація, а
// вимога: на RK3588 апаратний декодер один на всіх, і другий екземпляр
// mppvideodec конкурував би з показом за той самий mpp_service. Запис
// елементарного потоку коштує кілька відсотків одного ядра.
//
// ЗАТРИМКА ТУТ НЕ ВАЖЛИВА, і це дозволяє те, чого не можна на показі:
// великий буфер пересортування пакетів і глибока черга перед муксером.
// Записаний файл виходить кращим за те, що бачив пілот.

#include "storage.hpp"

#include <atomic>
#include <cstdint>
#include <memory>
#include <string>

namespace vrx::record {

struct RecordStats {
    bool active = false;         // пишемо просто зараз
    std::string file;            // поточний файл
    uint64_t bytes = 0;          // записано в поточний файл
    uint64_t total_bytes = 0;    // за весь час роботи
    uint32_t files = 0;          // скільки файлів створено
    uint32_t rotations = 0;      // з них через досягнення межі розміру
    uint32_t restarts = 0;       // з них через відновлення сигналу
    bool stream_alive = false;   // кадри приходять
};

class Recorder {
public:
    // Кодек і транспорт. MJPEG приходить СИРИМ JPEG по UDP, без RTP:
    // ні caps, ні depay, ні буфера пересортування там не буває — нема
    // ні номерів послідовності, ні чого переставляти.
    enum class Codec { H265, MJPEG };

    struct Config {
        // Ім'я потоку — потрапляє в назву файлу.
        std::string name = "main";

        Codec codec = Codec::H265;
        int udp_port = 5600;
        int payload_type = 97;

        // Буфер пересортування пакетів. На показі такий неприпустимий,
        // тут — чиста користь: втрачений і перепитаний пакет ще встигне
        // стати на місце, а порядок відновиться при перестановці.
        int jitter_ms = 200;

        // Черга перед муксером — МАЛЕНЬКА І З ВИТОКОМ.
        //
        // Спокуса зробити її великою природна: дешеві флешки пишуть
        // ривками й на секунди йдуть у себе, і хочеться цей ступор
        // пересидіти. Не працює. Черга — це рівно та кількість відео, що
        // лежить у пам'яті НЕЗАПИСАНОЮ, тобто пряма ціна висмикування
        // носія чи зникнення живлення. Заміряно: з чергою на 3 секунди
        // втрата при висмикуванні перевищила 20 секунд, а хвіст файлу
        // виявився сміттям.
        //
        // Тому як у старому VRX: 200 мс, 4 МБ, 60 буферів — і leaky.
        // При переповненні викидається НАЙСТАРІШИЙ кадр, а не блокується
        // гілка. Ступор флешки тоді коштує кількох кадрів запису замість
        // усього хвоста, і ніколи не підпирає нічого вище за течією.
        int queue_ms = 200;
        int queue_bytes = 4 * 1024 * 1024;
        int queue_buffers = 60;

        // Межа розміру сегмента. Менший файл легше переносити, а при
        // пошкодженні втрачається лише він.
        uint64_t rotate_bytes = 450ULL * 1024 * 1024;

        // Як часто просити носій скинути кеші.
        //
        // 5 секунд — значення, на якому зупинився старий VRX після
        // польотів. Я був прибрав періодичний syncfs узагалі, вирішивши,
        // що опція монтування "flush" (udisks ставить її знімним носіям)
        // уже забезпечує те саме. НЕ ЗАБЕЗПЕЧУЄ: замір на висмикуванні
        // дав утрату понад 20 секунд і напівбитий хвіст файлу.
        //
        // syncfs справді іноді впирається в ступор флешки на десятки
        // секунд, але з МАЛЕНЬКОЮ ЧЕРГОЮ це вже не страшно: вона просто
        // протікає, втрачаючи кадри, замість накопичувати незаписане.
        int sync_interval_ms = 5000;

        // Скільки без кадрів вважати, що сигнал зник. З запасом проти
        // звичайних мережевих пропусків: у польоті вони норма.
        int stream_lost_ms = 3000;

        // Скільки чекати дозапису при зупинці. Файл має закритися
        // коректно, інакше програвач побачить обрубок без індексу.
        int shutdown_flush_ms = 10000;

        // Починати файл СТРОГО з опорного кадру. Інакше перші кадри
        // посилаються на те, чого у файлі немає, і початок розсипається
        // квадратами.
        bool start_on_keyframe = true;
    };

    Recorder(Config cfg, Storage& storage);
    ~Recorder();

    Recorder(const Recorder&) = delete;
    Recorder& operator=(const Recorder&) = delete;

    // Піднімає власний потік. Далі клас живе сам: з'явився носій —
    // почав писати, зник — коректно закрив файл, сигнал пропав і
    // повернувся — відкрив новий.
    bool start();

    // Зупиняє запис, дочекавшись реального дозапису файлу.
    void stop();

    RecordStats stats() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::record
