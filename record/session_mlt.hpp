#pragma once

// ПРОЄКТ СЕАНСУ .mlt — один файл на вмикання станції.
//
// НАВІЩО. Записані файли самі по собі не складаються в перегляд: канали
// стартують і обриваються незалежно, файли ротуються за розміром, сигнал
// зникає й повертається. Щоб побачити політ, треба знати, який шматок де
// стоїть у часі, — і бажано не збирати це руками.
//
// .mlt — проєкт MLT, тобто те, що відкриває Shotcut і решта інструментів
// на його рушії. Всередині — доріжка на канал, шматки на своїх місцях і
// провали між ними. Скопіював теку дня на комп'ютер, відкрив один файл —
// і все стоїть, де стояло.
//
// ЧОМУ ОКРЕМИЙ ПОТІК, А НЕ РЕКОРДЕР. Проєкт переписується цілком, а не
// дописується: XML не має де дописувати, закривні теги стоять у кінці.
// Переписування на флешці блокує, і робити це з циклу рекордера означало б
// повторити помилку, через яку sync_file_range колись з'їв опитування
// проби й запис вирішив, що сигнал зник.
//
// ЧОМУ ЧИТАЄ ЖУРНАЛ, А НЕ СЛУХАЄ РЕКОРДЕРИ. index.jsonl і так пишеться,
// він append-only й переживає висмикування. Читати його — значить брати
// ті самі дані, що вціліють на носії, а не свою пам'ять, якої після
// вимкнення не буде. Заразом нуль зв'язків із рекордерами.

#include <memory>
#include <string>

namespace vrx::record {

class Storage;

class SessionMlt {
public:
    struct Config {
        // Мітка вмикання станції, вона ж ім'я проєкту: session_<мітка>.mlt.
        std::string session;

        // Як часто переписувати. Десять секунд — компроміс: проєкт завжди
        // свіжий із точністю до однієї мітки звірки, а флешку не тревожимо
        // дрібним записом частіше, ніж є що міняти.
        int period_ms = 10000;

        // Полотно проєкту. Береться під основний канал: він найбільший, і
        // саме він стоїть повним кадром.
        int width = 1920;
        int height = 1080;
        int fps_num = 60;
        int fps_den = 1;
    };

    SessionMlt(Config cfg, Storage& storage);
    ~SessionMlt();

    SessionMlt(const SessionMlt&) = delete;
    SessionMlt& operator=(const SessionMlt&) = delete;

    bool start();
    void stop();

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::record
