#pragma once

// ПЕРЕМОТКА ПО ФАЙЛУ, ЯКИЙ ПИСАВСЯ БЕЗ ТАБЛИЦІ ПЕРЕХОДІВ.
//
// Наші записи йдуть із streamable=true: назад по файлу муксер не
// повертається, тож ні тривалості, ні таблиці переходів у них немає навіть
// при штатному закритті. Ціна за те, що файл переживає висмикнуту флешку.
//
// Перемотка тримається на двох речах. Перша — журнал сеансу, який кожні
// п'ять секунд пише пару "PTS — записані байти", тобто рівно ту таблицю,
// якої бракує. Друга — оце: байтовий зсув із журналу вказує в СЕРЕДИНУ
// кластера, а демультиплексору треба подати його початок.
//
// Заміряно на справжньому записі: заголовок файлу займає 391 байт, і
// склейка "заголовок + кластер із середини" розбирається без помилок, із
// збереженням абсолютного часу.

#include <cstddef>
#include <cstdint>

namespace vrx::record {

// Скільки на початку файлу займає заголовок — усе до першого кластера.
// Саме ці байти подаються перед будь-яким шматком із середини.
// Повертає 0, якщо кластера в буфері немає.
size_t mkv_header_size(const uint8_t* buf, size_t n);

// Початок кластера на позиції не менше from. Повертає -1, якщо не знайшов.
//
// Кандидат ПЕРЕВІРЯЄТЬСЯ, а не береться на віру: чотирибайтова мітка
// кластера цілком може випадково трапитись усередині стисненого відео, і
// така "знахідка" дала б демультиплексору сміття. Перевірка проста й
// надійна — за міткою мусить іти розмір, а одразу за ним поле часу
// кластера; збіг усіх трьох умов на випадкових даних майже неможливий.
int64_t mkv_find_cluster(int fd, int64_t from, int64_t file_size);

} // namespace vrx::record
