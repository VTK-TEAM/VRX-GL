#pragma once

// ЗНІМОК КАДРУ В JPEG.
//
// Зберігає кадр У ПОВНІЙ РОЗДІЛЬНІЙ ЗДАТНОСТІ, а не так, як він зараз
// показаний на екрані: вікно можна зменшити до чверті, і знімок від цього
// втрачати нічого не повинен.
//
// ПОВІЛЬНО — десятки мілісекунд на кадр. Кликати з потоку показу не можна:
// це пропущені розгортки. Для того й винесено в окрему функцію, яку
// запускають на своєму потоці.

#include <cstdint>
#include <string>
#include <utility>
#include <vector>

namespace vrx::source { struct SourceFrame; }

namespace vrx::record {

bool save_jpeg(const source::SourceFrame& f, const std::string& path, int quality = 92);

// Набір кадрів однією міткою часу, у теку, на власному потоці.
//
// Мітка ОДНА на весь набір навмисно: інакше імена файлів розійшлися б на
// кілька мілісекунд, і зіставити знімки різних каналів між собою було б
// нічим. Мілісекунди в імені — це і є "кадр": на шістдесяти кадрах за
// секунду вони розрізняють сусідні, а секунди вже ні.
//
// Повертає кількість кадрів, узятих у роботу.
int save_set(std::vector<std::pair<std::string, source::SourceFrame>> frames,
             const std::string& dir, int64_t wall_us);

} // namespace vrx::record
