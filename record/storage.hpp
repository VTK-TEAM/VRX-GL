#pragma once

// Носій для запису: пошук, монтування, стан, синхронізація.
//
// ЄДИНА ТОЧКА ДОСТУПУ до флешки. Все, що чіпає носій, іде через цей
// клас — крім самого запису байтів, який робить GStreamer у пайплайні
// рекордера.
//
// ЧОМУ ОКРЕМИЙ ПОТІК, І ЧОМУ ЦЕ НЕ ПЕДАНТИЗМ. Виявлення носія робить
// stat(), access() і opendir() ПРЯМО на точці монтування. Це той самий
// клас блокуючого вводу-виводу, що й write(): коли носій фізично зникає
// посеред операції, ядро входить у SCSI error recovery, і будь-який
// виклик до цієї точки монтування — навіть просто "чи існує" — висить у
// D-стані реальні секунди. Процес у D-стані не переривається нічим.
//
// Тому: всі блокуючі дії живуть тут, у власних потоках, а назовні
// віддається лише ЗНІМОК стану. Читач ніколи не блокується, навіть якщо
// флешку висмикнули просто зараз.
//
// Потоків два, і теж не для краси: syncfs() на повільному USB під
// навантаженням триває секунди, і якби він жив у потоці опитування, то
// підвішував би виявлення носія рівно тоді, коли воно найпотрібніше.

#include <atomic>
#include <condition_variable>
#include <cstdint>
#include <mutex>
#include <string>
#include <thread>
#include <vector>

namespace vrx::record {

// Знімок стану носія. Копіюється цілком, живе окремо від Storage.
struct DriveState {
    bool present = false;      // є придатний носій
    std::string root;          // точка монтування, порожньо якщо немає

    uint64_t free_bytes = 0;
    uint64_t total_bytes = 0;

    // НОМЕР НОСІЯ. Росте щоразу, коли носій змінився: вставили, вийняли,
    // підмінили іншим. Рекордер порівнює саме його, а не шлях: та сама
    // точка монтування може дістатися вже іншій флешці, і дописувати в
    // "той самий" файл на ній не можна.
    uint32_t generation = 0;

    // Скільки минуло від останнього УСПІШНОГО опитування. Якщо росте —
    // потік опитування застряг на мертвому носії, і стан застарілий.
    int64_t age_ms = 0;

    // Скільки тривав останній syncfs. Пряма міра того, наскільки носій
    // повільний: якщо це наближається до інтервалу синхронізації, флешка
    // не встигає за потоком, і файл при зриві живлення втратить більше,
    // ніж здається з налаштувань.
    int64_t last_sync_ms = 0;
    int64_t max_sync_ms = 0;

    bool usable() const { return present && !root.empty(); }
};

class Storage {
public:
    struct Config {
        // Де шукати змонтовані носії — перевіряються прямі піддиректорії.
        std::vector<std::string> mount_roots = {"/media", "/mnt", "/run/media"};

        // Монтувати самому те, що система не змонтувала. Через
        // udisksctl, бо він робить це від імені користувача й без root.
        bool auto_mount = true;

        int poll_ms = 1000;

        // Скільки лишити вільним. Писати носій до нуля не можна: FAT/ext
        // на повному томі поводяться погано, а обірваний хвіст файлу
        // дорожчий за пару сотень мегабайтів.
        uint64_t reserve_bytes = 256ULL * 1024 * 1024;
    };

    explicit Storage(Config cfg);
    ~Storage();

    Storage(const Storage&) = delete;
    Storage& operator=(const Storage&) = delete;

    bool start();
    void stop();

    // Знімок. НІКОЛИ не блокується на вводі-виводі.
    DriveState state() const;

    // Шлях для нового файлу: <root>/<РРРР-ММ-ДД>/<РРРРММДД_ГГХХСС>_<ім'я>.<розш>
    // Створює директорію дати. Порожній рядок — не вдалося.
    //
    // Викликається з потоку рекордера й МОЖЕ заблокуватись: mkdir на
    // мертвому носії — таке саме блокуюче I/O. Це свідомо: рекордеру в
    // цей момент однаково нема чого робити, а от потік опитування таким
    // не отруюється.
    std::string make_path(const std::string& stream_name,
                          const std::string& ext = "mkv") const;

    // Просить скинути кеші на носій. Не блокує: syncfs робиться в
    // окремому потоці, і поки попередній не завершився, нові прохання
    // ігноруються.
    void request_sync();

    // Чи йде зараз syncfs. Для діагностики: якщо він висить хвилинами,
    // носій уже мертвий.
    bool sync_in_progress() const { return sync_busy_.load(std::memory_order_acquire); }

private:
    void probe_loop();
    void sync_loop();

    // Одна ітерація пошуку. Все блокуюче — тут.
    void probe_once();

    // Пробує змонтувати незмонтовані знімні розділи.
    void mount_removable();

    bool is_external(const std::string& path) const;

    Config cfg_;

    mutable std::mutex state_mtx_;
    DriveState state_;
    int64_t last_probe_ok_ns_ = 0;

    // st_dev кореня. Рахується один раз: усе, що на тому самому
    // пристрої, — не знімний носій, а сама система.
    uint64_t root_dev_ = 0;

    std::atomic<bool> running_{false};
    std::thread probe_thread_;

    std::thread sync_thread_;
    std::mutex sync_mtx_;
    std::condition_variable sync_cv_;
    bool sync_requested_ = false;
    std::atomic<bool> sync_busy_{false};

    // Придушення спаму: попередній надрукований стан.
    std::string last_log_;
};

} // namespace vrx::record
