#pragma once

// Словник розміщення: де на екрані показувати кадр.
//
// Тут НЕМАЄ класу, що володіє каналами. Розміщенням володіє саме
// джерело — воно самодостатнє й реєструється в рендерері само. Тут лише
// типи й арифметика, спільні для джерел і рендерера.
//
// Усе в частках 0..1 від верхнього лівого кута. Пікселів у логіці
// розкладки немає: монітори різні, а картинка має виглядати однаково.
// Та сама конвенція вже діє в osd_config.json старого проєкту.

namespace vrx::layout {

// ---------------------------------------------------------------------
// Якір
// ---------------------------------------------------------------------

// ЯКА ТОЧКА САМОГО ВІДЕО кріпиться до заданої координати.
//
// Не точка контейнера, а точка КАРТИНКИ — тієї, що реально видно після
// вписування за пропорцією. Різниця принципова: пропорція джерела
// міняється на ходу (електронна стабілізація ріже роздільність кропом,
// перезапуск потоку може дати інший формат), і від того, до чого
// прив'язана позиція, залежить, що станеться на екрані.
//
//   якір на КОНТЕЙНЕРІ  -> картинка їздить усередині нього, коли
//                          міняється пропорція; кут, який пілот бачив
//                          притиснутим до рогу, відходить від нього
//   якір на КАРТИНЦІ    -> обраний кут стоїть як укопаний, а зростає
//                          чи меншає протилежна сторона
//
// Сітка 3x3, назви читаються по рядках:
//
//     TopLeft      TopCenter      TopRight
//     CenterLeft   Center         CenterRight
//     BottomLeft   BottomCenter   BottomRight
enum class Anchor {
    TopLeft,     TopCenter,     TopRight,
    CenterLeft,  Center,        CenterRight,
    BottomLeft,  BottomCenter,  BottomRight,
};

struct AnchorFactor { float x, y; };

// Частка вільного місця, що лишається ПЕРЕД кадром по кожній осі.
// 0 — притиснуто до початку, 1 — до кінця, 0.5 — по центру.
constexpr AnchorFactor anchor_factor(Anchor a) {
    switch (a) {
        case Anchor::TopLeft:      return {0.0f, 0.0f};
        case Anchor::TopCenter:    return {0.5f, 0.0f};
        case Anchor::TopRight:     return {1.0f, 0.0f};
        case Anchor::CenterLeft:   return {0.0f, 0.5f};
        case Anchor::Center:       return {0.5f, 0.5f};
        case Anchor::CenterRight:  return {1.0f, 0.5f};
        case Anchor::BottomLeft:   return {0.0f, 1.0f};
        case Anchor::BottomCenter: return {0.5f, 1.0f};
        case Anchor::BottomRight:  return {1.0f, 1.0f};
    }
    return {0.5f, 0.5f};
}

// ---------------------------------------------------------------------
// Розміщення
// ---------------------------------------------------------------------

// Найменша дозволена коробка, частка екрана по кожній осі.
//
// Потрібна тому, що розмір приходить ззовні — телеметрією. Нуль або
// від'ємне зробили б картинку невидимою без жодної ознаки несправності:
// пілот бачив би чорний екран і не мав би способу зрозуміти, що це не
// втрата сигналу, а зіпсоване число. 5% екрана — це ще видимо і вже
// безглуздо, тобто добра межа для "щось не так".
constexpr float kMinSize = 0.05f;

// СТЕЛЯ РОЗМІРУ — ДВІ ПЛОЩІ ЕКРАНА, а не одна.
//
// Коробка більша за екран не є помилкою: це збільшення. Пілот наближає
// основний канал, щоб роздивитись деталь, і засуває зайве за край —
// показується та частина, яка лишилась на екрані. Доти стеля стояла на
// 1.0, і збільшити картинку було неможливо в принципі.
//
// Дві, а не безмежність: при більшому зумі на екрані лишається менше
// чверті кадру, і зорієнтуватись у ньому вже не виходить — а промахнутись
// колесом на кілька клацань легко.
constexpr float kMaxSize = 2.0f;

struct Placement {
    // ТОЧКА, ДО ЯКОЇ КРІПИТЬСЯ ЯКІР, у частках екрана від верхнього
    // лівого кута. Не кут прямокутника: до чого саме прикладається ця
    // точка, каже anchor, і прикладається вона до самої картинки.
    float x = 0.5f, y = 0.5f;

    // КОРОБКА, у яку вписується кадр: максимум, який йому дозволено
    // зайняти. Реальна картинка буде не більшою за неї, а по одній з
    // осей меншою, якщо пропорції не збігаються — чорні поля не
    // малюються, замість них просто менший прямокутник.
    float w = 1.0f, h = 1.0f;

    // Порядок малювання: більше — ближче до глядача. Обмін значеннями
    // між двома джерелами і є swap у PiP, без окремої гілки в коді.
    int z = 0;

    Anchor anchor = Anchor::Center;

    // Показувати цей кадр. Окремо від наявності джерела: "вимкнено
    // пілотом" і "сигналу немає" — різні події з різними причинами, і
    // злиття їх в один прапорець позбавило б можливості розрізнити.
    // Наявність сигналу джерело показує тим, що acquire() поверне false.
    bool enabled = true;
};

// ---------------------------------------------------------------------
// Вписування
// ---------------------------------------------------------------------

// Вписує кадр у коробку за пропорцією і ставить його так, щоб ОБРАНА
// ТОЧКА КАРТИНКИ опинилась рівно в (r.x, r.y).
//
// Чорні поля НЕ виникають: замість того щоб малювати їх, ми просто
// малюємо менший прямокутник.
//
//   src_aspect    — пропорція ВИДИМОЇ частини кадру (crop, не розмір
//                   буфера) з урахуванням неквадратних пікселів
//   screen_aspect — width / height екрана в пікселях
//
// Рахує рендерер і робить це ЩОКАДРУ: розмір джерела міняється в
// рантаймі — і при перезапуску потоку, і при вмиканні стабілізації,
// яка ріже роздільність кропом.
//
// ЯКІР НА КАРТИНЦІ, А НЕ НА КОРОБЦІ. Раніше кадр притискався до краю
// коробки: `out.x = r.x + (r.w - out.w) * k.x`. Різниця вилазить рівно
// тоді, коли пропорція джерела змінилась: при якорі на коробці картинка
// з'їжджала всередині неї, бо мінялася величина `r.w - out.w`. Тепер
// зсув рахується від самої картинки — `out.x = r.x - out.w * k.x`, — і
// обраний кут стоїть на місці незалежно від того, що сталося з
// пропорцією.
inline Placement fit_source(const Placement& r, float src_aspect, float screen_aspect) {
    Placement out = r;
    if (r.w <= 0.0f || r.h <= 0.0f || src_aspect <= 0.0f || screen_aspect <= 0.0f) {
        return out;
    }

    // Пропорція самої коробки в пікселях: у частках вона "квадратна",
    // але на екрані розтягується разом з екраном.
    const float box_aspect = (r.w / r.h) * screen_aspect;

    if (src_aspect > box_aspect) {
        out.h = r.w * screen_aspect / src_aspect;   // впираємось у ширину
    } else {
        out.w = r.h * src_aspect / screen_aspect;   // впираємось у висоту
    }

    // k — яку частку РОЗМІРУ КАРТИНКИ треба відступити назад від точки
    // якоря: 0 для лівого краю, 0.5 для середини, 1 для правого.
    const AnchorFactor k = anchor_factor(r.anchor);
    out.x = r.x - out.w * k.x;
    out.y = r.y - out.h * k.y;
    return out;
}

// Приводить розміщення до придатного вигляду. Кличеться там, де значення
// прийшли ЗЗОВНІ — з телеметрії, — і довіряти їм не можна.
//
// Позицію навмисно НЕ обмежуємо екраном: якір за краєм — законний спосіб
// показати частину картинки, і забороняти це означало б вирішувати за
// пілота. А от нульовий розмір нічого не показує взагалі.
inline Placement sanitize(Placement p) {
    if (!(p.w > kMinSize)) p.w = kMinSize;    // не (p.w <= kMin): ловить і NaN
    if (!(p.h > kMinSize)) p.h = kMinSize;
    if (p.w > kMaxSize) p.w = kMaxSize;
    if (p.h > kMaxSize) p.h = kMaxSize;
    if (!(p.x > -10.0f) || !(p.x < 10.0f)) p.x = 0.5f;   // NaN або дичина
    if (!(p.y > -10.0f) || !(p.y < 10.0f)) p.y = 0.5f;
    return p;
}

} // namespace vrx::layout
