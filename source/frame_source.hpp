#pragma once

// Джерело кадрів: усе, що хоче з'явитися на екрані.
//
// Кожне джерело самодостатнє: має власний потік, власні буфери, власне
// розміщення, і реєструється в рендерері само. Рендерер не знає, що це
// за джерело — лише питає кадр і малює його там, де сказано.
//
// НАПРЯМОК: питає РЕНДЕРЕР. Це дає дві речі безкоштовно. Темп задає той,
// хто показує (прокидається на vblank). І "перемагає найсвіжіший": якщо
// джерело встигло зробити два кадри між показами, проміжний просто
// перезаписався в слоті, і черга не росте. Для FPV це саме те — старий
// кадр нікому не потрібен.
//
// ТРИ БУФЕРИ на джерело, точніше три РОЛІ, між якими вони переставляються:
//
//     writing   декодер пише прямо зараз
//     ready     останній повний кадр, чекає на рендер
//     in_use    рендер зараз читає
//
// Коли декодер закінчив кадр: writing -> ready, а старий ready (якщо його
// не встигли забрати) повертається в обіг під writing. Ось тут і працює
// "перемагає найсвіжіший".
//
// На Rockchip є нюанс: mppvideodec має ВЛАСНИЙ пул і віддає кадри як
// GstSample. Тобто ми не даємо декодеру буфери, а тримаємо або відпускаємо
// посилання на його. Утримуємо максимум два (ready та in_use), тож пул
// декодера має бути щонайменше 3 — у mppvideodec зазвичай 8+, але це
// перше, що варто перевірити на новій платі, якщо картинка почне гикати.

#include "../display/display.hpp"
#include "../layout/layout.hpp"

#include <cstdint>

namespace vrx::source {

// ---------------------------------------------------------------------

struct SourceFrame {
    // Буфер кадру. Для джерел на dmabuf тут заповнено все; поле crop
    // задає ВИДИМУ частину, і саме з неї рахується пропорція. Це не
    // дрібниця: декодер віддає 1080 усередині 1088 (вирівнювання до
    // макроблоків), а електронна стабілізація ріже кадр кропом просто
    // на ходу.
    display::Frame image;

    // Неквадратні пікселі. Не завжди 1: наземна камера в старому проєкті
    // шле 720x480 (3:2), а зміст там 4:3.
    float pixel_aspect = 1.0f;

    // Де показувати. Іде РАЗОМ із кадром навмисно: інакше можна взяти
    // кадр нового розміру, а розміщення старе, і картинка смикнеться.
    layout::Placement where;

    // Коли кадр вийшов із декодера, CLOCK_MONOTONIC. Потрібне лише для
    // заміру наскрізної затримки "декодер -> пікселі на екрані" — це та
    // метрика, за якою тракт і оцінюється у FPV.
    int64_t produced_ns = 0;

    // Чи є що показувати. Окремо від image.valid(): геометрія може бути
    // відома й без реального буфера.
    bool valid() const { return image.width > 0 && image.height > 0; }

    // Пропорція для fit_source(): з видимої частини, не з буфера.
    float aspect() const {
        const display::Rect v = image.visible();
        return v.h > 0 ? (float(v.w) / float(v.h)) * pixel_aspect : 0.0f;
    }
};

struct SourceStats {
    uint64_t produced = 0;   // кадрів зроблено джерелом
    uint64_t taken = 0;      // кадрів забрав рендерер (нових)
    uint64_t dropped = 0;    // перезаписані до того, як їх забрали
    uint64_t reused = 0;     // показів, де нового кадру не було

    // КАДРИ, ЯКІ МАЛИ ПРИЙТИ Й НЕ ПРИЙШЛИ.
    //
    // Рахуються за ДІРКАМИ в приході: інтервал, що дорівнює двом-трьом
    // періодам, означає рівно те, що між сусідніми кадрами загубився
    // один-два. Причина може бути будь-де до нас — радіо, кодер на борті,
    // декодер, — і саме тому лічильник один: із приймальної сторони ці
    // випадки не розрізняються, а для пілота вони однакові.
    //
    // Не плутати з dropped: там кадр ДІЙШОВ і був викинутий нами як
    // застарілий, і це наша черга. Тут кадру не було взагалі.
    //
    // ПОВНА ВІДСУТНІСТЬ СИГНАЛУ СЮДИ НЕ ПОТРАПЛЯЄ. Діра, довша за
    // signal_timeout_ms, — це не втрачені кадри, а втрачений сигнал, і
    // рахувати її кадрами означало б за хвилину без камери накрутити
    // тисячі "втрат" і зробити лічильник непридатним саме тоді, коли по
    // ньому судять про якість лінка.
    uint64_t missing = 0;

    // ФАКТИЧНА частота джерела, по лічильнику кадрів на довгому вікні.
    // Не 60.000, навіть коли камера так каже: кварц у неї свій. Різниця
    // цієї частоти й частоти розгортки — те саме, що дрейф фази, тільки
    // виміряне навпростець і без обгортки. 0 = ще не виміряно.
    double produced_hz = 0;

    // Глибина черги на момент забирання. Якщо тримається біля нуля —
    // черга гасить парність декодера й затримки не додає. Якщо стоїть
    // повною — навпаки, кожен кадр чекає в ній зайвий період.
    double queue_avg = 0;
    int queue_max = 0;

    // Рівномірність приходу кадрів. Якщо min і max сильно різняться —
    // декодер віддає пачками, і жодна логіка на нашому боці цього не
    // виправить.
    double interval_min_ms = 0;
    double interval_max_ms = 0;
    double interval_avg_ms = 0;
};

// ---------------------------------------------------------------------

class FrameSource {
public:
    virtual ~FrameSource() = default;

    FrameSource(const FrameSource&) = delete;
    FrameSource& operator=(const FrameSource&) = delete;

    virtual const char* name() const = 0;

    // Піднімає й зупиняє ВЛАСНИЙ потік джерела.
    virtual bool start() = 0;
    virtual void stop() = 0;

    // Кличе рендерер щокадру, зі свого потоку. Питання — "ЩО ПОКАЗУВАТИ
    // ЗАРАЗ", а не "чи є щось свіже".
    //
    // Нового кадру немає -> віддати ПОПЕРЕДНІЙ. false означає рівно одне:
    // показувати нічого, тобто сигналу немає або джерело вимкнене.
    //
    // Плутати ці два стани не можна: джерело на 30 к/с проти показу на
    // 60 Гц має новий кадр лише через раз, і якщо на друге звернення
    // відповідати false, воно зникатиме з екрана кожен другий показ.
    // Симптом — мигання рівно на половині частоти джерела, якого НЕ
    // ВИДНО по жодному лічильнику.
    //
    // НЕ МАЄ ПРАВА БЛОКУВАТИ. Виклик іде з потоку показу, і будь-яке
    // очікування тут — це пропущений vblank. Усередині має бути лише
    // дешевий обмін під коротким локом: ніяких очікувань кадру, звернень
    // до GStreamer чи I/O.
    //
    // ЗВІЛЬНЕННЯ НЕЯВНЕ: наступний виклик acquire() означає, що з
    // попереднім кадром рендерер закінчив, і джерело може повернути той
    // буфер у пул. Це безпечно, бо між двома викликами рендерер завжди
    // дочекався fence — тобто GPU з попереднім кадром точно закінчив.
    //
    // ЯКЩО КОЛИСЬ З'ЯВИТЬСЯ КОНВЕЄР ("малюємо N+1, поки показуємо N"),
    // інваріант зламається і знадобиться явний release(). Помилка була б
    // тихою: розриви в картинці без жодного повідомлення в лозі.
    virtual bool acquire(SourceFrame& out) = 0;

    virtual layout::Placement placement() const = 0;
    virtual void set_placement(const layout::Placement& p) = 0;

    virtual SourceStats stats() const = 0;

    // Чи є ЗАРАЗ сигнал (кадр приходив не давніше за signal_timeout).
    // Потрібне сценарію "останній вцілілий потік — на весь екран":
    // розкладка має знати, скільки джерел живі прямо зараз.
    virtual bool has_signal() const = 0;

protected:
    FrameSource() = default;
};

} // namespace vrx::source
