#pragma once

// Приймання й декод H.265 з UDP.
//
// Самодостатнє джерело: власний потік, власний пайплайн GStreamer,
// власний нагляд за станом. Ззовні — той самий FrameSource, що й у
// решти: рендерер не знає, що це декодер.
//
// Пайплайн узято з VRX, де він налітаний і стабільний, але без гілки
// tee. Заразом прибрано дві милиці, які існували ВИКЛЮЧНО через tee:
// примусовий hvc1-capsfilter і другий h265parse, що конвертував назад у
// byte-stream. У старому коді сказано прямо: без явного hvc1 парсер
// "з'їжджає" в byte-stream, щойно поруч з'являється сусід-парсер. Без
// tee сусіда немає, і h265parse домовляється з mppvideodec напряму.
//
// Буфери НЕ наші: mppvideodec має власний пул і віддає кадри як
// GstSample. Ми лише утримуємо посилання, решту крутить декодер.
//
// СКІЛЬКИ САМЕ ми утримуємо — питання не риторичне, бо на стільки ж
// треба збільшити пул декодера, інакше він упреться в порожнечу і
// почне гальмувати сам себе:
//
//     до kMaxQueue (3) у черзі  +  1 у in_use  =  до 4
//
// Кадр, який зараз малює рендерер, окремої посилки не додає: він
// ділить keepalive з in_use.
//
// Це СТЕЛЯ, досяжна лише коли рендерер надовго став. У роботі глибину
// тримає активне зливання в acquire(), і заміряно вона 0.93 при
// максимумі 1 — тобто утримуємо два буфери.

#include "frame_source.hpp"

#include <string>

#include <memory>
#include <string>

namespace vrx::source {

class VideoSource : public FrameSource {
public:
    struct Config {
        int udp_port = 5600;
        int payload_type = 97;

        // Скільки часу без ЖОДНОГО кадру вважати, що сигналу немає.
        // Тільки після цього acquire() поверне false і джерело зникне з
        // екрана; заглушок не малюємо, бо програма одна, а дрони різні.
        //
        // 3 секунди, а не менше, свідомо. У польоті декодер регулярно
        // не віддає частину кадрів: пробої лінка, втрачені пакети,
        // очікування наступного IDR після биття. Це НОРМА, а не втрата
        // сигналу — рендер має її взагалі не помічати й далі показувати
        // останній валідний кадр, ніби нічого не сталося.
        //
        // Коротший таймаут перетворив би кожен пробій на блимання
        // картинкою, що гірше за підвисання на частку секунди.
        int signal_timeout_ms = 3000;

        // Скільки терпіти "дані в декодер ідуть, а кадрів немає", перш
        // ніж перезбирати пайплайн.
        //
        // Помітно більше за signal_timeout_ms, і це навмисно: три
        // секунди без кадру на битому лінку — НОРМА, яку ми свідомо
        // терпимо. Перезбирання на кожен пробій було б гірше за сам
        // пробій.
        //
        // Реально це рятує не політ, а ЗАПУСК: якщо негоціація не
        // склалася або декодер став на старті, станція підніметься сама
        // замість того, щоб мовчки показувати чорне.
        int restart_after_ms = 10000;

        // Цільова глибина черги ПІСЛЯ забирання кадру.
        //
        // Черга потрібна лише щоб гасити парність декодера: він віддає
        // два кадри майже одночасно (заміряно: інтервал min 0.2 мс), а
        // потім мовчить до 34 мс. Пара покриває два показè, пауза
        // покриває себе — тобто запасу в ОДИН кадр досить.
        //
        // Глибше не треба й шкідливо. Джерело (60.00) трохи швидше за
        // показ (59.789), тож без активного зливання черга набирається
        // до стелі й ЗАСТРЯГАЄ там назавжди: сама вона не розсмокчеться,
        // бо частоти майже рівні. Заміряно на стелі 3 — черга стояла на
        // 2.5 і давала 37 мс постійної затримки. Це не буфер, а зсув.
        //
        // Тому надлишок скидається з ГОЛОВИ при кожному заборі. Ми й так
        // зобов'язані викидати ~0.21 кадру/с через різницю частот —
        // краще робити це найстарішими, ніж накопичувати затримку.
        int target_queue = 0;
    };

    VideoSource(std::string name, Config cfg);
    ~VideoSource() override;

    const char* name() const override;

    bool start() override;
    void stop() override;

    // Перемкнути вхідний UDP-порт на ходу. Пайплайн перезбирається на новий
    // порт; на "лівому" порту кадри не надходять і картинка застигає на
    // останньому. Використовується ліцензійним саботажем.
    void set_udp_port(int port);

    bool acquire(SourceFrame& out) override;

    layout::Placement placement() const override;
    void set_placement(const layout::Placement& p) override;

    SourceStats stats() const override;

    // Діагностика: чи є зараз сигнал, і який розмір кадру бачимо.
    bool has_signal() const;

    // Інтервали між кадрами на ВХОДІ декодера, мс. Порівняння з
    // інтервалами на виході (SourceStats) показує, чи створює декодер
    // парність сам.
    void input_intervals(double* min_ms, double* avg_ms, double* max_ms) const;

    // Час від подачі зібраного кадру в декодер до його появи в нашому
    // буфері, мс. Тобто чистий декод без мережі й без показу.
    void decode_latency(double* min_ms, double* avg_ms, double* max_ms) const;
    int frame_width() const;
    int frame_height() const;

protected:
    // ---------------------------------------------------------------
    // ГАЧКИ ДЛЯ НАЩАДКІВ: усе, чим канали різняться, і нічого більше.
    //
    // Решта — черга, звільнення буферів, замір інтервалів, детекція
    // сигналу, витягання dmabuf — однакова для будь-якого кодека й
    // живе тут, у базі.
    // ---------------------------------------------------------------

    // Caps для udpsrc. ПОРОЖНЬО = без фільтра взагалі: так треба, коли
    // потік іде без RTP-обгортки й описувати нічого.
    virtual std::string caps() const = 0;

    // Ланка від udpsrc до входу декодера: depay, parse і, якщо треба,
    // явний capsfilter перед декодером.
    //
    // ФОРМАТ НА СТИКУ ПИНИТЬСЯ ТУТ, а не лишається на розсуд негоціації.
    // Раніше база вміла перебирати варіанти цієї ланки, якщо домовитись
    // не вдалося. Механізм прибрано: камера — наша ж прошивка, потік
    // сталий, і вгадувати нема чого. А перебір був місцем для глюку —
    // див. журнал у README.
    virtual std::string parse_chain() const = 0;

    // Сам декодер. Має віддавати dmabuf, інакше кадри мовчки гинуть на
    // імпорті в текстуру.
    virtual std::string decoder() const = 0;

    // Налаштування — нащадкам потрібен хіба що номер payload.
    const Config& config() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::source
