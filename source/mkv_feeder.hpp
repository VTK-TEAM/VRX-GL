#pragma once

// ПОДАВАЧ БАЙТІВ ЗАПИСУ — те, що стоїть перед appsrc замість filesrc.
//
// Навіщо власний, а не filesrc. Наші записи не мають таблиці переходів
// (streamable=true), тож перемотка йде не запитом до демультиплексора, а
// стрибком у байтовий зсув із журналу сеансу. Демультиплексор при цьому
// не побачить заголовка файлу — а без нього він не знає ні кодека, ні
// доріжок.
//
// Тому подавач робить склейку: спершу віддає ЗАГОЛОВОК (усе до першого
// кластера, заміряно — 391 байт), а далі байти з потрібного місця. Проба
// на живому записі показала, що ланцюжок matroskademux ! h265parse !
// mppvideodec ковтає таке без жодної помилки, зі збереженням абсолютного
// часу.
//
// МЕЖА ЧИТАННЯ. Для сеансу, який ЩЕ ПИШЕТЬСЯ, читати можна лише до
// останньої мітки журналу: далі неї дані можуть ще не дійти до носія, і
// хвіст файлу буде недописаним кластером.

#include <cstdint>
#include <string>
#include <vector>

namespace vrx::source {

class MkvFeeder {
public:
    ~MkvFeeder();

    // Відкриває файл і зчитує заголовок. Далі його можна віддавати скільки
    // завгодно разів — після кожної перемотки він потрібен знову.
    bool open(const std::string& path);
    void close();

    // Стрибок. byte_hint — зсув із мітки журналу; він указує в СЕРЕДИНУ
    // кластера, тому справжній початок шукається вперед від нього.
    // Заголовок після цього подається наново.
    bool seek(int64_t byte_hint);

    // Скільки байтів файлу вважати надійними. -1 = увесь файл (сеанс
    // закритий). Для живого сеансу — safe_bytes останньої мітки.
    void set_limit(int64_t bytes);

    // Наступна порція для appsrc. 0 означає кінець доступних даних —
    // для живого сеансу це тимчасово, і після оновлення межі читання
    // триває далі.
    size_t read(uint8_t* out, size_t max);

    int64_t header_size() const { return (int64_t)header_.size(); }
    int64_t position() const { return pos_; }
    int64_t size() const { return size_; }

private:
    int fd_ = -1;
    std::vector<uint8_t> header_;
    size_t header_sent_ = 0;
    int64_t pos_ = 0;
    int64_t size_ = 0;
    int64_t limit_ = -1;
};

} // namespace vrx::source
