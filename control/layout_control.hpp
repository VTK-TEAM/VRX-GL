#pragma once

// Розкладка з телеметрії: де на екрані стоять основний канал і PiP.
//
// ЧОМУ ТЕЛЕМЕТРІЯ, А НЕ СВІЙ КАНАЛ. Спокуса зробити окремий сокет
// природна — свій протокол, свій формат, нічого не заважає. Але канал
// керування в польоті має бути живим тоді ж, коли живе все інше, а
// телеметрія вже прокладена, вже має CRC і вже перевірена годинами
// роботи. Другий канал означав би друге місце, яке ламається, і другий
// набір причин "чому не подіяло".
//
// Тому station просто слухає десять каналів у тому самому потоці
// телеметрії (150..159, див. vt_telemetry_index.h) і застосовує їх до
// джерел. Хто їх шле — борт, наземний пульт чи скрипт на столі — цьому
// класу байдуже.
//
// ЩО САМЕ ВІН РОБИТЬ. Раз на такт читає сховище телеметрії, збирає з
// каналів `Placement` і віддає джерелу. Уся геометрія — вписування за
// пропорцією, якір на КАРТИНЦІ, мінімальний розмір — живе в layout.hpp і
// рахується рендерером щокадру; тут лише перенесення чисел.
//
// ВЛАСНИЙ ПОТІК, як і в решти підсистем: main покадрових викликів не має.
// Такт 100 мс — це реакція на перемикач, а не покадрова робота; частіше
// не має сенсу, бо саме число приходить із телеметрією разів десять на
// секунду в кращому разі.

#include "../layout/layout.hpp"
#include "../osd/telemetry/vt_telemetry_storage.h"
#include "../source/frame_source.hpp"

#include <memory>
#include <string>
#include <vector>

namespace vrx::control {

class LayoutControl {
public:
    struct Config {
        int period_ms = 100;

        // СЦЕНАРІЙ "ОСТАННІЙ ВЦІЛІЛИЙ — НА ВЕСЬ ЕКРАН". Якщо сигнал є рівно
        // в ОДНОГО джерела (неважливо якого), воно розтягується на весь
        // екран, ігноруючи розкладку з телеметрії. Щойно оживає друге —
        // повертається задана розкладка. Сенс: коли лишається один потік,
        // тримати його маленьким PiP чи в кутку немає причини.
        bool solo_fullscreen = true;
    };

    // Одне джерело й п'ятірка каналів, що ним керує. Список задається
    // явно: класу не треба знати, скільки джерел у станції і які саме —
    // це справа main, як і скрізь у цьому проєкті.
    struct Bound {
        std::shared_ptr<source::FrameSource> source;
        std::string name;                  // для логу

        uint8_t ch_w = 0, ch_h = 0, ch_x = 0, ch_y = 0, ch_anchor = 0;

        // ЩО СТОЇТЬ, ПОКИ КЕРУВАННЯ МОВЧИТЬ. Не нулі: станція має
        // показувати осмислену картинку одразу після ввімкнення, ще до
        // того, як хтось узагалі щось надішле.
        layout::Placement fallback;
    };

    explicit LayoutControl(Config cfg);
    ~LayoutControl();

    LayoutControl(const LayoutControl&) = delete;
    LayoutControl& operator=(const LayoutControl&) = delete;

    // Прив'язки задаються до старту й далі не міняються.
    void bind(Bound b);

    bool start(VtTelemetryStorage& storage);
    void stop();

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::control
