#pragma once

// Фазове автопідстроювання камери під розгортку екрана.
//
// ЩО ЦЕ РОБИТЬ. Камера й монітор мають незалежні кварци. Навіть 0.03 Гц
// різниці на 60 Гц означають, що момент приходу кадру повільно повзе по
// періоду розгортки, і раз на кілька секунд неминуче перетинає точку
// опитування рендерера: кадр або показується двічі, або гине. По
// лічильниках це "дроп 0.4/с, повтор 0.4/с", оком — мікрофриз.
//
// Керуємо ЧАСТОТОЮ камери (`fpsTrimMilliHz`), а фаза виходить сама:
//
//     фаза = ∫ (частота_камери − частота_екрана) dt
//
// Тобто камера — генератор, керований напругою, а ця петля — звичайна
// ФАПЧ. Друга ручка камери, `sendPhaseMs`, теж зсуває фазу, але робить
// це затримкою відправки — тобто платить за зсув наскрізною затримкою.
// Частота платить нулем, тому тут використовується лише вона.
//
// ЗВІДКИ БЕРУТЬСЯ ВИМІРИ. Три різні підсистеми, і саме тому петля живе
// окремим класом, а не всередині якоїсь із них:
//   - період розгортки   -> DisplayManager (лічильник vblank'ів ядра);
//   - фаза приходу кадру -> GlRenderer (рахує від vblank до produced_ns);
//   - живість сигналу    -> FrameSource (лічильник узятих кадрів).
//
// ОБМЕЖЕННЯ: рендерер міряє фазу по НАЙНОВІШОМУ кадру серед усіх
// джерел. Поки реальні мітки часу ставить лише декодер (у TestSource
// produced_ns лишається нулем), це і є фаза камери. Щойно з'явиться
// друге справжнє джерело, фазу доведеться міряти окремо для кожного —
// інакше петля почне ловити не ту камеру.

#include "camera_api.hpp"

#include "../display/display_manager.hpp"
#include "../render/gl_renderer.hpp"
#include "../source/frame_source.hpp"

#include <memory>
#include <string>

namespace vrx::control {

struct PhaseStats {
    bool engaged = false;      // петля веде камеру (є всі виміри й сигнал)
    bool locked = false;       // помилка тримається в межах lock_ms
    const char* holding = "";  // якщо не engaged — чому саме

    double display_hz = 0;     // опорна частота, виміряна по vblank'ах
    double period_ms = 0;
    double phase_ms = 0;       // де в періоді опиняється прихід кадру
    double target_ms = 0;      // куди ведемо
    double error_ms = 0;       // зі знаком, по колу

    int trim_mhz = 0;          // що зараз стоїть на камері
    uint64_t sent = 0;         // скільки разів записали
    uint64_t failed = 0;       // скільки записів не пройшло
};

class PhaseController {
public:
    struct Config {
        CameraApi::Config camera;

        // Префікс параметра в API камери: "video0" -> "video0.fpsTrimMilliHz".
        std::string param = "video0";

        // Куди вести фазу, мс від vblank'а. Від'ємне значення = АВТО:
        // центр вікна прийому, тобто максимально далеко від обриву.
        //
        // ЩО ТАКЕ ВІКНО. Рендерер опитує джерела за poll_offset_ms після
        // vblank'а і показує зведене на наступному vblank'у. Кадр, що
        // встиг до опиту, їде на екран із затримкою (період − фаза);
        // кадр, що спізнився на мікросекунду, чекає ЦІЛИЙ зайвий період.
        // Отже функція затримки — пила з обривом рівно в точці опиту.
        //
        // Центр вікна = poll_offset − період/2. Там до обриву однаково
        // далеко з обох боків (~8.3 мс на 60 Гц), тобто мережевий джитер
        // не здатний перекинути кадр через край. Ціна — затримка сідає
        // на середину пили, ~13 мс замість ~5 мс біля самого обриву.
        //
        // Це свідомий розмін: біля обриву кожен виплеск джитера коштує
        // повного зайвого періоду й видимого ривка.
        double target_phase_ms = -1.0;

        // Період роботи петлі. Запит до камери блокує, тому справжній
        // крок часу міряється, а не припускається.
        int update_ms = 500;

        // ПІ-регулятор. Вихід — мГц підстроювання камери, вхід — мс
        // помилки фази. Зв'язок з фізикою:
        //
        //     дрейф_фази[мс/с] = −підстроювання[мГц] / частота[Гц]
        //
        // (камера швидша -> кадри приходять дедалі раніше -> фаза падає).
        //
        // Значення підібрано симуляцією об'єкта разом із ЗАТРИМКОЮ
        // вимірювання: рендерер віддає фазу через ЕМА з постійною ~0.8 с,
        // і саме вона ставить стелю. Перевірено по сітці стартових фаз і
        // розбіжностей кварців ±200 мГц:
        //
        //     kp=30  ki=3.8   ζ=1.0   захоплення 20 с
        //     kp=45  ki=8.4   ζ=1.0   захоплення 12.5 с   <- взято
        //     kp=60  ki=15    ζ=1.0   захоплення 9 с
        //     kp=80  ki=26.7  ζ=1.0   НЕ СХОДИТЬСЯ (затримка фільтра)
        //
        // ζ=1 навмисно: перерегулювання тут означає проїхати обрив пили,
        // тобто зайвий дубль кадру просто в процесі підстроювання.
        double kp_mhz_per_ms = 45.0;
        double ki_mhz_per_ms_s = 8.4;

        // Межа з боку камери (±2000 мГц). Реально треба одиниці-десятки.
        int trim_limit_mhz = 2000;

        // Не смикати камеру через дрібниці.
        int min_step_mhz = 2;

        // Перезапис того самого значення. Потрібен НЕ для керування:
        // підстроювання на камері не зберігається між запусками, тож
        // після її перезавантаження воно мовчки стане нулем. Періодичний
        // перезапис повертає петлю в дію за heartbeat_ms замість "ніколи".
        int heartbeat_ms = 5000;

        // Розігрів: скільки чекати, поки встановляться вимір частоти
        // (потрібна секунда vblank'ів) і фільтр фази в рендерері.
        int warmup_ms = 3000;

        // Межа для позначки "захоплено".
        double lock_ms = 0.5;
    };

    PhaseController(display::DisplayManager& display,
                    render::GlRenderer& renderer,
                    std::shared_ptr<source::FrameSource> source,
                    Config cfg);
    ~PhaseController();

    PhaseController(const PhaseController&) = delete;
    PhaseController& operator=(const PhaseController&) = delete;

    // Піднімає власний потік. Ззовні петлю ніхто не крутить.
    bool start();

    // Зупиняє потік і повертає камері номінальну частоту.
    void stop();

    PhaseStats stats() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::control
