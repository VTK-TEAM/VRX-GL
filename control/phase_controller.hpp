#pragma once

// Фазове автопідстроювання камери під розгортку екрана.
//
// ЩО ЦЕ РОБИТЬ. Камера й монітор мають незалежні кварци. Навіть 0.03 Гц
// різниці на 60 Гц означають, що момент приходу кадру повільно повзе по
// періоду розгортки, і раз на кілька секунд неминуче перетинає точку
// опитування рендерера: кадр або показується двічі, або гине. По
// лічильниках це "дроп 0.4/с, повтор 0.4/с", оком — мікрофриз.
//
// Керуємо ЧАСТОТОЮ камери (`fpsTrimMilliHz`), а фаза виходить сама:
//
//     фаза = ∫ (частота_камери − частота_екрана) dt
//
// Тобто камера — генератор, керований напругою, а ця петля — звичайна
// ФАПЧ. Друга ручка камери, `sendPhaseMs`, теж зсуває фазу, але робить
// це затримкою відправки — тобто платить за зсув наскрізною затримкою.
// Частота платить нулем, тому тут використовується лише вона.
//
// ЗВІДКИ БЕРУТЬСЯ ВИМІРИ. Три різні підсистеми, і саме тому петля живе
// окремим класом, а не всередині якоїсь із них:
//   - період розгортки   -> DisplayManager (лічильник vblank'ів ядра);
//   - фаза приходу кадру -> GlRenderer (рахує від vblank до produced_ns);
//   - живість сигналу    -> FrameSource (лічильник узятих кадрів).
//
// ЯКА САМЕ КАМЕРА. Фаза береться з ПЕРШОГО зареєстрованого джерела, а
// не з найновішого кадру серед усіх. Різниця істотна: другий канал має
// власний кварц і власну затримку, і якби його кадри потрапляли у вимір,
// петля ловила б то одну камеру, то іншу — і не спіймала б жодної.
//
// Немає сигналу в першого — фаза просто не оновлюється цього кадру.
// Підміняти її другим каналом не можна: вести камеру за чужою фазою
// гірше, ніж не вести взагалі.

#include "camera_api.hpp"

#include "../display/display.hpp"
#include "../render/gl_renderer.hpp"
#include "../source/frame_source.hpp"

#include <memory>
#include <string>

namespace vrx::control {

struct PhaseStats {
    bool engaged = false;      // петля веде камеру (є всі виміри й сигнал)
    bool locked = false;       // помилка тримається в межах lock_ms
    const char* holding = "";  // якщо не engaged — чому саме

    double display_hz = 0;     // опорна частота, виміряна по vblank'ах
    double period_ms = 0;
    double phase_ms = 0;       // де в періоді опиняється прихід кадру
    double target_ms = 0;      // куди ведемо
    double error_ms = 0;       // зі знаком, по колу

    double poll_ms = 0;        // де обрив: точка опиту рендерера
    double jitter_ms = 0;      // виміряний розкид приходу (сигма)
    double guard_ms = 0;       // на скільки відступили від обриву
    double latency_ms = 0;     // що з цього виходить: період − фаза

    int trim_mhz = 0;          // що зараз стоїть на камері
    uint64_t sent = 0;         // скільки разів записали
    uint64_t failed = 0;       // скільки записів не пройшло ЗА ВЕСЬ ЧАС
    bool last_write_failed = false;  // чи впав ОСТАННІЙ — саме це тривожно
};

class PhaseController {
public:
    struct Config {
        CameraApi::Config camera;

        // Префікс параметра в API камери: "video0" -> "video0.fpsTrimMilliHz".
        std::string param = "video0";

        // КУДИ ВЕДЕМО ФАЗУ. Від'ємне значення (типове) = рахувати саму,
        // додатне = стала ціль у мс від vblank'а, для перевірок.
        //
        // Геометрія. Рендерер опитує джерела за poll_offset_ms після
        // vblank'а і показує зведене на наступному vblank'у. Кадр, що
        // встиг до опиту, їде на екран із затримкою (період − фаза);
        // кадр, що спізнився на мікросекунду, чекає ЦІЛИЙ зайвий період.
        // Отже затримка як функція фази — пила з ЄДИНИМ обривом, рівно в
        // точці опиту.
        //
        // Обрив один, і тільки з боку "пізно". Тому запас потрібен теж
        // односторонній: стояти якнайближче до опиту, але не ближче, ніж
        // виплеск джитера здатний перекинути кадр через край.
        //
        //     ціль = poll_offset − guard_sigmas * розкид
        //
        // Обидва множники ВИМІРЯНІ, а не задані числом, і саме тому ціль
        // рахується щокроку:
        //   - poll_offset їде, бо він = період − час_зведення, а зведення
        //     подорожчає, щойно з'явиться OSD;
        //   - розкид залежить від налаштувань борту (шейпер на 48 Мбіт/с
        //     давав 8.6 мс, без нього 2.9).
        // Стала цифра була б правильною рівно для однієї конфігурації.
        //
        // Сьогоднішні числа на 60 Гц: опит 11.8, розкид 2.9 -> ціль 6.0,
        // затримка 10.7 мс.
        double target_phase_ms = -1.0;

        // ЗАПАС ДО ТОЧКИ ОПИТУ — величина СТАЛА, а не порахована з
        // поточного розкиду.
        //
        // Раніше тут стояло guard = 4σ, де σ — згладжений розкид фази,
        // виміряний прямо зараз. Ідея була в тому, щоб автоматично
        // тримати запас рівно під поточний джитер. На вимірі виявилось,
        // що ціна цього більша за користь: σ гуляє від такту до такту, і
        // ціль разом із нею. За 5-хвилинний прогін ціль мала σ 0.41 мс, і
        // 23% усієї дисперсії похибки петлі виявились рухом ЦІЛІ, а не
        // фази. Тобто чверть роботи петля робила навздогін самій собі.
        //
        // Запас має бути поблажливим до джитера, а не підлаштованим під
        // нього. Число взято з того самого заміру, що й раніше, — 4σ при
        // σ≈1.85 мс, — але зафіксовано:
        //
        // Заміряно 28.07.2026 на живому лінку (σ=1.7 мс):
        //     3σ -> запас 3.9 мс, затримка  8.6 мс, 0.37  збою/с (104 с)
        //     4σ -> запас 4.9 мс, затримка 10.5 мс, 0.042 збою/с (312 с)
        //     5σ -> запас 6.6 мс, затримка 12.9 мс, 0.035 збою/с (144 с)
        //
        // 4σ — робоча точка. Третя сигма купує дев'ятикратне зменшення,
        // п'ята не купує НІЧОГО: різниця 0.042 проти 0.035 лежить у межах
        // шуму (13 подій проти 5), а затримка росте на 2.4 мс. Тобто за
        // 4σ хвіст джитера вичерпано, і решта збоїв має іншу природу.
        //
        // Розподіл приходу має хвости товщі за гаусові: на 2σ гаус давав
        // би 1.1/с, а насправді 1.8/с. Тому запас підбирається заміром, а
        // не з таблиці нормального розподілу.
        //
        // Якщо джитер на лінку суттєво зміниться, це число треба
        // переміряти — але саме переміряти й переставити, а не доручати
        // петлі совати його на кожному такті.
        // 6.5 = 4σ при σ≈1.6 мс — те, що адаптивна формула й видавала на
        // цьому лінку. Перша спроба зафіксувати дала 7.5, і це коштувало
        // 1.4 мс наскрізної затримки просто так: запас вийшов 4.9σ, а за
        // четвертою сигмою хвіст джитера вже вичерпано.
        double guard_ms = 6.5;

        // Період роботи петлі. Запит до камери блокує, тому справжній
        // крок часу міряється, а не припускається.
        int update_ms = 500;

        // ДВІ ЛАНКИ, І ЦЕ ПРИНЦИПОВО.
        //
        // Фаза — інтеграл різниці частот. Тому здобувати сталий частотний
        // зсув із фази означає інтегрувати те, що само вже є інтегралом:
        // накопичене з'їдається щоразу, коли фаза обертається й помилка
        // міняє знак. Перевірено на залізі — при різниці 857 мГц петля
        // тільки метлялася (+21, +318, −475), бо потрібні їй −904 мГц
        // лежать поза межами пропорційної ланки (kp × півперіоду = 382).
        //
        // Тому:
        //   ЧАСТОТУ веде інтегратор по ВИМІРЯНОМУ дрейфу фази. Дрейф
        //   обгортки не має взагалі, тож інтеграл накопичується чесно;
        //   ФАЗУ веде пропорційна ланка поверх нього.
        //
        //     дрейф[мс/с] -> різниця частот[мГц] = −дрейф × 1000 / період
        //     тримінг = частотна_ланка + kp × помилка_фази
        //
        // Частотна ланка сходиться за кілька кроків і далі стоїть; фазова
        // лише утримує позицію й на рівновазі дорівнює нулю.
        double kp_mhz_per_ms = 45.0;

        // Частка нев'язки частоти, що застосовується за крок.
        //
        // Мусить бути ЗНАЧНО меншою за швидкодію фазової ланки, і це не
        // обережність, а умова роботи. Обидві ланки крутять ту саму ручку,
        // тож якщо їхні смуги перетинаються, вони починають боротись:
        // фазова вводить частотний зсув, щоб посунути фазу, частотна
        // прибирає його як помилку. На 0.35 це дало розгойдування з
        // заходом фази за точку опиту.
        //
        // 0.01 за такт у 0.5 с — стала близько 50 секунд.
        //
        // Було 0.10 (стала 5 с), і це виявилось налаштуванням під об'єкт,
        // якого немає. Контрольний прогін із --no-phase показав, що
        // розстройка кварців камери й екрана — 1029 мГц зі стабільністю
        // σ 0.5 мГц за 5 хвилин. Це константа.
        //
        // Ланка ж інтегрує ОЦІНКУ ДРЕЙФУ, а та береться регресією на
        // вікні 2 с по середніх, кожне з яких має шум 0.47 мс. Сусідні
        // такти беруть вікна з перекриттям 7/8, тож шум оцінки ще й
        // корельований — інтегратор від такого блукає далеко. Заміряно:
        // тримінг гуляв із σ 36 мГц, тобто в 70 разів сильніше за те, що
        // він компенсує, і саме це давало 1.7 мс блукання фази, якого на
        // вільному ходу камери немає взагалі.
        //
        // Смуга частотної ланки має відповідати об'єкту: кварц ходить від
        // нагріву за хвилини, отже й ланці потрібні десятки секунд.
        double kf_per_step = 0.01;

        // Підсилення актуатора: скільки мГц справжньої зміни дає один мГц
        // команди. Заміряно на камері по семи точках у діапазоні
        // 0…−1500: 0.95. Петля стійка й без цієї поправки, але з нею
        // частотна ланка сходиться за один крок замість трьох.
        double actuator_gain = 0.95;

        // Межі команди. Знизу — рейка камери. Зверху НУЛЬ, і це не
        // обережність: матриця не вміє прискорюватись вище за апаратну
        // стелю режиму, тож додатна команда просто гине. Петля, яка її
        // видає, вважає, що діє, а насправді стоїть.
        //
        // Саме тому розгортка опущена до 59 Гц: рівновага має лежати
        // всередині діапазону. Щойно прошивка навчиться піднімати
        // частоту — тут міняється одна цифра.
        int trim_limit_mhz = 3000;
        int trim_max_mhz = 0;

        // Не смикати камеру через дрібниці.
        int min_step_mhz = 2;

        // Перезапис того самого значення. Потрібен НЕ для керування:
        // підстроювання на камері не зберігається між запусками, тож
        // після її перезавантаження воно мовчки стане нулем. Періодичний
        // перезапис повертає петлю в дію за heartbeat_ms замість "ніколи".
        int heartbeat_ms = 5000;

        // Розігрів: скільки чекати, поки встановляться вимір частоти
        // (потрібна секунда vblank'ів) і фільтр фази в рендерері.
        int warmup_ms = 3000;

        // Межа для позначки "захоплено".
        double lock_ms = 0.5;
    };

    PhaseController(display::Display& display,
                    render::GlRenderer& renderer,
                    std::shared_ptr<source::FrameSource> source,
                    Config cfg);
    ~PhaseController();

    PhaseController(const PhaseController&) = delete;
    PhaseController& operator=(const PhaseController&) = delete;

    // Піднімає власний потік. Ззовні петлю ніхто не крутить.
    bool start();

    // Зупиняє потік і повертає камері номінальну частоту.
    void stop();

    PhaseStats stats() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::control
