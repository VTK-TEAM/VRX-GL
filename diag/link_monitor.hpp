#pragma once

// Спостерігач лінка: що саме сталося, коли відео підвисло.
//
// НАВІЩО ОКРЕМА РІЧ. Лічильники рендерера кажуть "кадру не було", і на
// цьому зупиняються. Але "не було" має дві різні причини з протилежним
// лікуванням:
//
//   пакети загубилися в дорозі  -> лінк, антени, потужність, завади;
//   камера нічого не слала      -> борт, кодер, живлення, прошивка.
//
// Розрізняє їх РІВНО ОДНЕ: номери послідовності RTP. Якщо після паузи
// нумерація йде поспіль — камера мовчала. Якщо в ній діра — пакети
// загубилися. По самих лише мітках часу приходу ці випадки НЕ
// відрізнити, і саме через це попереднє розслідування довелося
// закінчити словом "імовірно".
//
// Слухає той самий порт власним сокетом: борт шле бродкастом, ядро
// віддає копію кожної датаграми кожному сокету на порту. Пакети лише
// читаються — жодного впливу ні на показ, ні на запис.
//
// ЛИШЕ ДЛЯ RTP. Другий канал іде сирим JPEG без обгортки, номерів там
// немає взагалі, тож і рахувати нічого.

#include <atomic>
#include <cstdint>
#include <memory>
#include <string>

namespace vrx::diag {

struct LinkStats {
    uint64_t packets = 0;      // прийнято датаграм
    uint64_t lost = 0;         // не долетіло, за дірами в нумерації
    uint64_t reordered = 0;    // прийшли не по порядку
    uint64_t dups = 0;         // прийшли двічі
    double loss_percent = 0;

    // Паузи в приході, довші за поріг.
    uint32_t gaps = 0;
    uint32_t gaps_with_loss = 0;   // з дірою в нумерації = винен лінк
    uint32_t gaps_clean = 0;       // нумерація ціла = мовчала камера

    int64_t last_gap_ms = 0;
    bool last_gap_had_loss = false;
    int64_t worst_gap_ms = 0;
};

class LinkMonitor {
public:
    struct Config {
        std::string name = "main";
        int udp_port = 5600;

        // Від якої тиші вважати подією. 100 мс — це вже шість кадрів на
        // 60 к/с, тобто помітно оком; дрібніші пропуски рахуються в
        // загальну втрату, але окремими подіями не стають.
        int gap_ms = 100;

        // Куди писати інциденти. Порожньо — лише в stderr.
        std::string log_path;
    };

    explicit LinkMonitor(Config cfg);
    ~LinkMonitor();

    LinkMonitor(const LinkMonitor&) = delete;
    LinkMonitor& operator=(const LinkMonitor&) = delete;

    bool start();
    void stop();

    LinkStats stats() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::diag
