#pragma once

// Локальні канали телеметрії: те, що станція знає про СЕБЕ.
//
// Борт шле свої числа по радіо, але частина показань на екрані —
// властивість самої наземки, і взятися їм більше нізвідки: скільки
// кадрів реально прийшло кожним потоком, скільки з них дійшло до
// екрана, з якою частотою екран їх показує, чи йде запис і на що.
//
// У VRX це рахував головний цикл програми. Тут так не можна: main не
// має покадрової роботи, і кожна підсистема живе власним потоком. Тому
// це окремий клас із власним потоком, який раз на пів секунди опитує
// підсистеми й кладе результат у те саме сховище, що наповнює приймач
// телеметрії. Далі числа нічим не відрізняються від бортових: їх однаково
// малює OSD і однаково пише писар субтитрів.
//
// ЧОМУ ОПИТУВАННЯ, А НЕ ПОВІДОМЛЕННЯ. Підсистеми не знають про OSD і не
// повинні: рекордер не має слати телеметрію, а джерело — знати, що його
// лічильники комусь показують. Знімок стану кожна з них і так віддає
// (`stats()`), і цей знімок ніколи не блокується.
//
// Канали (vt_telemetry_index.h, локальні >= 200):
//
//     200  RECORDING_STATE   0 немає носія / 1 пише / 2 носій є, не пише
//                            "пише" = активний БУДЬ-ЯКИЙ рекордер (осн.,
//                            PiP чи захват), а не лише основний
//     201  LINE_LOSS         SFP_TX_POINT − SFP_RX_STATION, дБ
//     202  H265_FPS          прийнято й декодовано основним каналом
//     203  MJPEG_FPS         те саме для другого каналу
//     204  H265_SHOWN_FPS    скільки з них ДІЙШЛО до екрана
//     205  DISPLAY_FPS       з якою частотою екран показує взагалі
//     206  PHASE_LOCK        стан ФАПЧ: 0 не веде / 1 веде / 2 захоплено
//     207  LATENCY_MS        затримка тракту: декодер -> підтверджений показ
//     208  DROPPED_FPS       кадрів на секунду, що не дійшли до екрана
//     209  LATE_FPS          кадрів на секунду, що прийшли після опиту
//
// Пара 202/204 нарізно не випадкова: якщо перше є, а друге менше —
// кадри губляться не в лінку й не в декодері, а вже на показі.
//
// Четвірка 206..209 — це стан тракту показу, і читати її треба разом.
// Порізно кожне число бреше: затримка буває маленькою саме тому, що
// кадри летять повз екран, а нуль пропусків стоїть і при затримці в два
// періоди. 209 тут ключове й ніде більше не видиме: кадр, що спізнився
// на опит, не втрачений і не повторений — усі звичні лічильники його
// показують здоровим, — але поїде на екран на розгортку пізніше.

#include "telemetry/vt_telemetry_storage.h"

#include "../control/phase_controller.hpp"
#include "../display/display.hpp"
#include "../record/recorder.hpp"
#include "../record/storage.hpp"
#include "../render/gl_renderer.hpp"
#include "../source/frame_source.hpp"

#include <memory>

namespace vrx::osd {

class LocalChannels {
public:
    struct Config {
        // Період опитування. Пів секунди — стільки ж, скільки у VRX:
        // швидше не має сенсу, бо саме на такому вікні рахується
        // частота, а повільніше вже помітно на око як застигла цифра.
        int period_ms = 500;
    };

    explicit LocalChannels(Config cfg);
    ~LocalChannels();

    LocalChannels(const LocalChannels&) = delete;
    LocalChannels& operator=(const LocalChannels&) = delete;

    // Усе, що опитується, передається явно. Довгий список — це чесно:
    // клас і є місцем, де сходяться підсистеми, і краще бачити це в
    // сигнатурі, ніж ховати за глобальним реєстром.
    //
    // Будь-яке джерело може бути nullptr: немає другого каналу — просто
    // не буде каналу 203, а не падіння.
    bool start(VtTelemetryStorage& storage,
               const display::Display& display,
               const render::GlRenderer& renderer,
               const control::PhaseController& phase,
               const record::Recorder& rec,
               const record::Storage& drive,
               std::shared_ptr<source::FrameSource> h265,
               std::shared_ptr<source::FrameSource> mjpeg,
               std::shared_ptr<source::FrameSource> capture = nullptr,
               // Вторинні рекордери. Індикатор запису (200) показує "пише",
               // якщо активний хоч один із трьох — інакше при вимкненому
               // основному пілот бачив би "не пише", хоча захват іде.
               const record::Recorder* rec_pip = nullptr,
               const record::Recorder* rec_cap = nullptr);

    void stop();

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::osd
