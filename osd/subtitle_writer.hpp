#pragma once

// Телеметрія в субтитри поруч із записаним відео.
//
// Перенесено з VRX (OSD/osd_subtitle_writer.*). Формат той самий — .ass
// з абсолютним позиціюванням, тож плеєр малює телеметрію рівно там, де
// вона стояла на екрані. Файл лягає поруч із .mkv і має те саме ім'я:
//
//     2026-07-28_14-03-11_main.mkv
//     2026-07-28_14-03-11_main.ass          розкладка з osd_config.json
//     2026-07-28_14-03-11_main.debug.ass    таблиця всіх каналів
//
// ДВА ФАЙЛИ, ОДИН ПОТІК. У VRX кожен режим мав власний екземпляр із
// власним потоком, хоча обидва робили те саме: раз на пів секунди
// прокидались і питали стан запису. Тут один потік пише обидва файли —
// цикл опитування спільний, а знімки різняться лише вмістом.
//
// ЧОМУ ОКРЕМИЙ ПОТІК, А НЕ ВИКЛИК ІЗ РЕНДЕРА. Це не стиль, а вимога.
// Файл лежить на знімному носії, і якщо флешку висмикнути просто під
// час write(), ядро (SCSI error recovery на USB) може не повертати
// керування РЕАЛЬНІ СЕКУНДИ. У VRX це вже ловилось: головний потік
// опинявся в D-стані саме в момент витягування, і разом із ним ставав
// увесь показ. Тому все, що чіпає носій, живе окремо — так само, як
// syncfs у record::Storage.
//
// СИНХРОНІЗАЦІЯ З ЗАПИСОМ. Писар не вирішує, коли починати: він
// стежить за рекордером основного каналу через RecordStats. Пішов
// новий файл — відкривається новий .ass, зупинився запис — файли
// закриваються. Часова шкала субтитрів рахується від початку запису,
// а не від старту програми, інакше субтитри роз'їхалися б із відео на
// весь час, що програма працювала до появи носія.

#include "telemetry/vt_telemetry_storage.h"
#include "../record/recorder.hpp"
#include "../record/storage.hpp"

#include <memory>
#include <string>

namespace vrx::osd {

struct SubtitleStats {
    bool active = false;      // пишемо просто зараз
    std::string file;         // поточний .ass
    uint64_t snapshots = 0;   // знімків записано
    uint64_t files = 0;       // файлів відкрито
};

class SubtitleWriter {
public:
    struct Config {
        // Той самий конфіг, що читає OSD: субтитри мають повторювати
        // екран, а не жити власною розкладкою.
        // ЛИШЕ ОСНОВНИЙ ЕКРАН, і це навмисно. Розкладок телеметрії тепер
        // дві — osd_config.json і osd_config2.json, — але субтитри лягають
        // до ОДНОГО відеофайлу основного каналу. Розкладці другого екрана
        // там нема на що накластися: інший кадр, інший вміст.
        std::string config_json = "osd_config.json";

        std::string layout_suffix = ".ass";
        std::string debug_suffix = ".debug.ass";

        // Дебажну таблицю всіх каналів можна вимкнути: вона велика й
        // потрібна для розбору польоту, а не для перегляду.
        bool write_debug = true;

        // Період знімка. 2 Гц — стільки ж, скільки у VRX: телеметрія
        // приходить не частіше, а кожен знімок це десятки рядків .ass.
        int snapshot_ms = 500;

        // PlayRes у заголовку .ass — має відповідати роздільності
        // ЗАПИСАНОГО відео, а не екрана: плеєр масштабує субтитри під
        // кадр, і при розбіжності телеметрія з'їде відносно картинки.
        int video_w = 1920;
        int video_h = 1080;
    };

    explicit SubtitleWriter(Config cfg);
    ~SubtitleWriter();

    SubtitleWriter(const SubtitleWriter&) = delete;
    SubtitleWriter& operator=(const SubtitleWriter&) = delete;

    // Читає osd_config.json. Без нього писар мовчки нічого не пише —
    // це не привід валити запис відео.
    bool init();

    // Піднімає власний потік.
    //
    //   rec     — за ним синхронізується: новий файл запису тягне новий
    //             .ass, зупинка запису їх закриває;
    //   drive   — носій. Питається через той самий клас, що й рекордери,
    //             і з тієї ж причини: точка монтування може дістатися
    //             ІНШІЙ флешці, тож звіряється НОМЕР носія, а не шлях;
    //   storage — телеметрія, та сама, що наповнює приймач OSD.
    bool start(const record::Recorder& rec,
               const record::Storage& drive,
               VtTelemetryStorage& storage);
    void stop();

    SubtitleStats stats() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::osd
