#pragma once

// ЗАПИСАНА ТЕЛЕМЕТРІЯ — субтитри .ass, які станція пише поруч із відео.
//
// Формат вибрано не нами й не заради нас: .ass дає готовий шар телеметрії
// для будь-якого стороннього плеєра, і саме тому він там і з'явився. Але
// він же виявився найзручнішим і для власного плеєра — це рівно те, що
// показував OSD у ту секунду, з тими самими підписами й на тих самих
// місцях.
//
// Читається ВЕСЬ файл одразу: навіть за довгий політ це кількасот тисяч
// коротких рядків, тобто одиниці мегабайтів, а шукати по часу треба
// швидко й багато разів.

#include <cstdint>
#include <string>
#include <vector>

namespace vrx::osd {

class AssTrack {
public:
    struct Line {
        int64_t start_us = 0;
        int64_t end_us = 0;
        float x = 0, y = 0;        // координати В ПРОСТОРІ ЗАПИСУ (PlayRes)
        std::string text;
    };

    bool load(const std::string& path);
    bool empty() const { return lines_.empty(); }

    // Розмір полотна, у якому задані координати. Плеєр показує запис у
    // вікні довільного розміру, тож без цього масштабувати нема від чого.
    int play_w() const { return play_w_; }
    int play_h() const { return play_h_; }

    // Рядки, активні в цю мить. Порядок — як у файлі: спершу підписи
    // розкладки, далі значення, і накладаються вони так само, як писались.
    void at(int64_t t_us, std::vector<const Line*>& out) const;

private:
    std::vector<Line> lines_;
    int play_w_ = 1920, play_h_ = 1080;
};

} // namespace vrx::osd
