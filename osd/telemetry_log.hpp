#pragma once

// ЛОГ ТЕЛЕМЕТРІЇ — сирі значення, бінарно, поруч із відео.
//
// НАВІЩО, якщо є субтитри. Субтитри несуть телеметрію ВЖЕ НАМАЛЬОВАНУ:
// текст відформатовано й розставлено за тією розкладкою, що діяла під час
// запису. Показати те саме за іншою розкладкою — скажімо, за розкладкою
// другого екрана — з них уже не вийде, а розкладок у нас дві.
//
// Сирі значення цього обмеження не мають: плеєр згодовує їх у той самий
// OSD, і той малює звичним шляхом — з поточною розкладкою, іконками,
// правилами приховування. Заразом лог відкриває те, чого в субтитрах
// немає взагалі: канали, які на екран не виводились.
//
// ФОРМАТ (порядок байтів — прямий, little-endian).
//
// Заголовок, 32 байти:
//   0   "VRXT"        4    підпис
//   4   u16 version   2    = 1
//   6   u16 channels  2    скільки пар у кадрі
//   8   i64 epoch_us  8    настінний час першого кадру, мікросекунди
//   16  u16 frame_ms  2    крок між кадрами
//   18  u16 frame_len 2    довжина кадру в байтах
//   20  u32 meta_len  4    довжина блоку опису, що йде далі
//   24  8 байтів резерву, нулі
//
// Блок опису, meta_len байтів: звичайний текст, рядки "ключ=значення" —
// format, version, session, build, channels, frame_ms, frame_len, epoch_us.
//
// Таблиці імен каналів тут немає: набір id сталий і читачеві відомий. А от
// їхня КІЛЬКІСТЬ із часом міняється, тож файл несе її в собі — інакше
// запис, зроблений торік, довелося б читати, підбираючи версію коду.
//
// Кадри починаються з 32 + meta_len. Оскільки кадр сталого розміру, це
// не заважає рахувати його номер прямо з часу.
//
// Кадр, frame_len байтів:
//   u32 t_ms                       від epoch
//   channels × { u16 id; f32 val } NaN, якщо каналу ще не було
//
// КАДР СТАЛОГО РОЗМІРУ — і це головне рішення формату. Значення пишуться
// всі щоразу, навіть незмінні й невживані. Виглядає марнотратно: близько
// одинадцяти мегабайтів на годину проти гігабайтів відео. Натомість дає
// доступ за часом БЕЗ ЖОДНОГО СКАНУВАННЯ: номер кадру — це час, поділений
// на крок. Ні індексу, ні ключових кадрів, ні розбору — ні тут, ні в
// майбутній програмі на комп'ютері.

#include <memory>
#include <string>

class VtTelemetryStorage;

namespace vrx::record { class Storage; }

namespace vrx::osd {

class TelemetryLog {
public:
    struct Config {
        std::string session;       // мітка вмикання, вона ж ім'я файлу
        int frame_ms = 500;        // крок; телеметрія й так оновлюється двічі на секунду
        int channels = 256;        // скільки id писати
    };

    TelemetryLog(Config cfg, VtTelemetryStorage& storage, record::Storage& drive);
    ~TelemetryLog();

    bool start();
    void stop();

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::osd
