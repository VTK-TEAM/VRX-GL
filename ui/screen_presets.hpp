#pragma once

// Екрани-пресети: ТРИ збережені розкладки відео-вікон, редаговані мишею.
//
// Окремий оверлей і ЄДИНИЙ власник геометрії вікон. Приймає рішення сам:
//   - який пресет активний — 3-позиційний перемикач на пульті (канал 15,
//     ПО ЗМІНІ) або три кнопки 1/2/3 зліва вгорі (мишею);
//   - де стоять вікна в активному пресеті — перетяг лівою кнопкою і
//     масштаб колесом (аспект зберігається, впираємось лише в краї
//     екрана, накладання дозволено);
//   - автозбереження кожного пресета у свій файл через 5 с без дій.
//
// Логіка вводу живе в acquire() (потік показу — дешево, без блокувань), а
// запис у файли виносить окремий потік: I/O в потоці показу коштував би
// vblank'ів.
//
// Замінює керування розкладкою з телеметрії (LayoutControl): тепер
// авторитет один. (Edge-приведення телеметрії 150..164 у пресети —
// наступним кроком.)

#include "../layout/layout.hpp"
#include "../osd/telemetry/vt_telemetry_storage.h"
#include "../render/overlay.hpp"
#include "../render/scene.hpp"
#include "../source/frame_source.hpp"
#include "pointer.hpp"

#include <functional>
#include <memory>
#include <string>
#include <vector>

namespace vrx::ui {

class ScreenPresets : public render::Overlay {
public:
    struct Config {
        // Файли пресетів: <prefix>1.json, <prefix>2.json, <prefix>3.json.
        std::string file_prefix = "screen";
        int preset_count = 3;

        float button_size = 0.03f;   // висота кнопки, частка висоти екрана
        float wheel_step = 0.06f;    // масштаб за один тік колеса
        int autosave_ms = 5000;

        // Перемикач екранів: канал + пороги 3 позицій.
        // Канал пульта, яким перемикаються пресети. У розкладці v2 канали
        // пультів лежать блоками по 32 на джерело, тож п'ятнадцятий канал
        // першого пульта — це 192 + 14.
        uint16_t switch_channel = 206;       // VT_TLM_RC1_CH1 + 14
        // Пороги — у МІКРОСЕКУНДАХ: борт тепер шле канали вже переведеними
        // в µs (1000 низ / 1500 центр / 2000 верх), а не сирим CRSF. Пороги
        // стоять на серединах між позиціями 3-позиційного тумблера.
        int thr_low = 1250, thr_high = 1750; // <low=1, ≤high=2, >high=3
    };

    // Одне кероване вікно.
    // РЕЖИМ ЕКРАНА. Той самий механізм вікон обслуговує і ефір, і плеєр:
    // вони рухаються мишею, мають пресети й кнопки однаково. Різниця лише
    // в тому, чиї кадри показують, — а це вирішує, який набір вікон зараз
    // увімкнено на цій ролі.
    //
    // Дублювати заради плеєра всю механіку пресетів було б гірше, ніж
    // здається: дві копії одного коду з часом розходяться, і другий екран
    // починає поводитись "майже так само".
    enum Mode { kLive = 0, kPlayer = 1, kModes = 2 };

    struct Window {
        std::string name;                            // ключ у файлі
        std::shared_ptr<source::FrameSource> source;
        layout::Placement fallback;                  // якщо файлу пресета ще немає
        int mode = kLive;                            // до якого набору належить

        // ЧИЄ ЦЕ ВІКНО. -1 = спільне для обох екранів (так живуть ефірні:
        // одне джерело, показане на обох). Плеєри ж свої на кожному екрані,
        // і без цього поля вікна чужого плеєра вилазили б на сусідній
        // екран, щойно той теж перейшов би в режим плеєра.
        int role = -1;

        // ПРОПОРЦІЯ ВІКНА БЕЗ ВІДЕО (ширина/висота в пікселях). Вікно може
        // й не мати джерела: аудіометр — така сама рухома річ на екрані, з
        // тією ж механікою й тим самим збереженням, але малює його свій
        // шар. Тоді пропорцію не взяти з кадру, і її задають тут.
        float aspect = 0.f;
    };

    explicit ScreenPresets(Config cfg);
    ~ScreenPresets() override;

    ScreenPresets(const ScreenPresets&) = delete;
    ScreenPresets& operator=(const ScreenPresets&) = delete;

    void attach(Pointer* pointer);
    void add_window(Window w);
    void set_telemetry(VtTelemetryStorage* tlm);   // для перемикача каналом 15; може бути nullptr

    const char* name() const override { return "presets"; }
    void attach_scene(render::Scene* scene);

    // Перемкнути роль між ефіром і плеєром. Вікна іншого набору стають
    // вимкненими в сцені, тобто рендерер їх просто не малює — жодного
    // окремого шляху показу для плеєра не з'являється.
    //
    // Активний пресет у кожного набору СВІЙ: перемикання 1/2/3 у плеєрі не
    // має чіпати розкладку ефіру, це різні задачі й різні розкладки.
    void set_mode(int role, int mode);

    // Сповіщення про перемикання — кнопкою або програмно. Пресети про
    // плеєр нічого не знають: відкрити сеанс має той, хто ним володіє.
    void set_on_mode(std::function<void(int role, int mode)> cb);

    // ОБЛАСТЬ, ЗАЙНЯТА ЧУЖИМ ШАРОМ. Пресети поводяться з нею так само, як
    // зі своїми кнопками: вікно під нею не обирається й не тягнеться.
    //
    // Без цього перетяг повзунка таймлайну заразом тягнув би відео, яке
    // під ним лежить, — миша ж одна, і обидва шари бачать те саме
    // натискання.
    void set_blocked_area(std::function<bool(int role, float cx, float cy)> cb);

    // Знімок ефіру. Куди складати файли, пресети не знають — це справа
    // того, хто володіє носієм.
    void set_on_shot(std::function<int(int role)> cb);
    int mode(int role) const;

    // Чи розгорнутий ряд кнопок на цій ролі.
    bool menu_open(int role) const;

    // ЧИ ПОПРОСИЛИ РЕДАКТОР розкладки — кнопкою в ряду. Одноразовий:
    // прочитали — згас, тож натискання не спрацює двічі.
    //
    // Кнопка редактора — ЗВИЧАЙНА кнопка ряду, як OSD чи плеєр: та сама
    // плитка, той самий клік, позиція з ряду; лише на основному екрані
    // (там відкривається редактор), останньою в ряду. Раніше вона
    // жила окремим шаром зі своїм зашитим номером слота й ламалась із
    // кожною новою кнопкою в ряду.
    bool take_editor_request();

    // --- ЗВУК: кнопка-динамік і аудіометр ---
    //
    // Пресети тримають лише те, що про ВІКНА: де стоїть метр і чи його
    // показано (це частина розкладки й лягає в screenN.json), і саму
    // кнопку в ряду. Панель гучності, малювання рівня й збереження
    // гучності — окремий шар AudioUi, як і таймлайн плеєра.
    //
    // Метр — вікно з іменем "meter" без джерела (add_window).

    // Чи розгорнута панель звуку під кнопкою (лише при відкритому меню).
    bool audio_popup(int role) const;
    // Прямокутник кнопки-динаміка, частки екрана, 0 = верх.
    void audio_button_rect(int role, float* x, float* y, float* w, float* h) const;
    // Прямокутник метра, якщо він показаний на цій ролі зараз (ефір,
    // прапорець активного пресета). Інакше false.
    bool meter_rect(int role, float* x, float* y, float* w, float* h) const;
    bool meter_visible(int role) const;
    void toggle_meter(int role);

    bool start() override;
    void stop() override;
    void set_frame_size(int role, int width, int height) override;
    const std::vector<render::OverlayImage>& images() const override;
    bool acquire(int role, render::DrawList& out) override;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::ui
