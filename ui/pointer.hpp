#pragma once

// Миша на голому Linux: читаємо evdev напряму.
//
// ЧОМУ НЕ БІБЛІОТЕКА. Станція працює без X і без будь-якого віконного
// стеку — брати мишу нізвідки, крім /dev/input. Це, зрештою, і не
// складно: ядро віддає готові події з полями type/code/value, а все, що
// нам потрібно, — два лічильники й одна кнопка.
//
// ЯК ЗНАХОДИМО МИШУ. Не за іменем і не за номером: імена в різних
// пристроїв різні, а номер їде від того, що ще ввімкнено в USB. Питаємо
// саму здатність — пристрій має вміти ВІДНОСНІ координати (EV_REL з
// REL_X/REL_Y) і мати ліву кнопку. Тачпади й миші під це підходять, а
// клавіатури, кнопки живлення й HDMI-детектори — ні.
//
// ВЛАСНИЙ ПОТІК, як і в решти підсистем. Назовні — лише знімок стану:
// читач ніколи не блокується, а сам потік сидить на poll() і не крутить
// процесор даремно.
//
// КООРДИНАТИ В ПІКСЕЛЯХ ЕКРАНА. Миша дає приріст, а не позицію, тож межі
// має знати саме цей клас — інакше курсор поїде за край і назад не
// повернеться.

#include <cstdint>
#include <utility>
#include <vector>
#include <memory>

namespace vrx::ui {

struct PointerState {
    // НА ЯКОМУ ЕКРАНІ зараз курсор — роль, а не слот (0 основний,
    // 1 додатковий). Малює його лише той екран, чий номер тут стоїть.
    int screen = 0;
    int x = 0, y = 0;          // піксели ЦЬОГО екрана
    bool left = false;         // ліва кнопка натиснута ЗАРАЗ
    uint64_t clicks = 0;       // скільки разів натискали ліву за весь час
    bool right = false;        // права кнопка натиснута ЗАРАЗ
    uint64_t rclicks = 0;      // скільки разів натискали праву за весь час
    bool middle = false;       // колесо НАТИСНУТЕ зараз (BTN_MIDDLE)
    uint64_t mclicks = 0;      // скільки разів натискали колесо за весь час
    // Колесо — НАКОПИЧУВАЛЬНО (як clicks): читач бере дельту від свого
    // попереднього значення. + вгору (від себе), - вниз. Не всі миші його
    // мають; за відсутності просто стоїть на нулі.
    int64_t wheel = 0;
    bool present = false;      // хоч один пристрій знайдено
};

class Pointer {
public:
    struct Config {
        // Прискорення: скільки пікселів на одиницю приросту. Одиниця —
        // "як є", повільно й точно; більше — швидше й грубіше.
        float speed = 1.0f;
    };

    explicit Pointer(Config cfg);
    Pointer();
    ~Pointer();

    Pointer(const Pointer&) = delete;
    Pointer& operator=(const Pointer&) = delete;

    // Межі задає той, хто знає розмір екрана. До виклику курсор стоїть у
    // нулі й нікуди не рухається.
    void set_bounds(int width, int height);

    // ЕКРАНИ, ПО ЯКИХ ХОДИТЬ КУРСОР, у порядку ролей.
    //
    // Курсор живе в КІЛЬЦІ: вийшов за лівий край — з'явився праворуч на
    // сусідньому, і навпаки. Кільце, а не "лівий/правий", навмисно: так
    // не треба описувати, який монітор де стоїть фізично, а обійти всі
    // екрани можна в будь-який бік.
    //
    // По вертикалі позиція ведеться ЧАСТКОЮ висоти, а не пікселями:
    // екрани бувають різної висоти, і перехід на середині має лишатись
    // серединою, а не з'їжджати вгору.
    void set_screens(const std::vector<std::pair<int, int>>& sizes);

    bool start();
    void stop();

    // Знімок. Не блокується.
    PointerState state() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::ui
