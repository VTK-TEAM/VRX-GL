#pragma once

// АПІ виводу — єдина точка, через яку решта програми говорить з екраном.
//
// Тут НЕМАЄ реалізації, лише інтерфейс: вивід буде різний на різному
// залізі, і міняти його треба без правок у споживачах.
//
// ОДИН ШАР. Свідомо. Багатоплейновість більше не є поняттям цього АПІ —
// не тому, що плейнів мало, а тому що покладатися на них не можна: на
// RK3588 незалежних вікон із лінійним NV12 чотири, а на RK3566 — рівно
// одне (Cluster приймає лише AFBC, Smart лише RGB). Архітектура, що
// вимагає трьох плейнів, на половині цільового заліза просто не існує.
//
// Тому зведення відео, PiP і OSD живе ВИЩЕ цього АПІ, у рендерері. Сюди
// приходить уже готовий кадр. Дисплей знає лише дві речі: що він уміє
// показати (LayerInfo) і як показати те, що дали (submit + present).
//
// ЧОМУ "Layer", а не "Plane". Плейн — апаратна сутність DRM, якої в
// GL-бекенді не існує. Назва, прив'язана до однієї реалізації, зробила б
// заміну реалізації самообманом.

#include <cstdint>
#include <functional>
#include <memory>
#include <string>
#include <vector>

namespace vrx::display {

// ---------------------------------------------------------------------
// Опис кольору
// ---------------------------------------------------------------------

enum class ColorSpace {
    Unknown,
    BT601,
    BT709,      // типове для FPV-лінка
    BT2020,
};

enum class ColorRange {
    Unknown,
    Limited,    // 16..235, типове для відео
    Full,       // 0..255
};

// Що фізично йде в кабель. Не плутати з форматом буфера (fourcc): буфер
// у нас RGB завжди, а на виході драйвер може віддавати YCbCr — і за
// замовчуванням часто саме так і робить, обираючи режим за EDID.
//
// Це має значення: RGB-буфер -> YCbCr у кабель -> RGB усередині монітора
// це дві конверсії там, де могло не бути жодної, з ризиком розʼїхатись на
// межах діапазону (чорне/біле). Вибір, зроблений драйвером мовчки, ще й
// різний на різних моніторах — тому пінимо явно.
enum class ColorFormat {
    Unknown,
    RGB,
    YCbCr444,
    YCbCr422,
    YCbCr420,
};

// ---------------------------------------------------------------------
// Геометрія
// ---------------------------------------------------------------------

struct Rect {
    int x = 0, y = 0, w = 0, h = 0;

    bool empty() const { return w <= 0 || h <= 0; }
    bool operator==(const Rect& o) const {
        return x == o.x && y == o.y && w == o.w && h == o.h;
    }
    bool operator!=(const Rect& o) const { return !(*this == o); }
};

// ---------------------------------------------------------------------
// Метадані шару — усе, що рендереру треба знати, щоб зробити правильний кадр
// ---------------------------------------------------------------------

struct LayerInfo {
    // Розмір. Шар завжди на весь екран, тож це і є роздільність монітора.
    int width = 0;
    int height = 0;

    // Частота в МІЛІгерцах: 60000 == 60.000 Гц. Ціле число навмисно —
    // "60 Гц" рідко буває рівно 60, а різниця з реальною частотою
    // джерела визначає, як часто кадр зсуватиметься на наступну
    // розгортку. Округлення до цілих герц цю інформацію б знищило.
    int refresh_mhz = 0;

    // Формат, у якому шар очікує кадри, і його модифікатор розкладки.
    uint32_t fourcc = 0;        // DRM_FORMAT_*
    uint64_t modifier = 0;      // DRM_FORMAT_MOD_* (LINEAR, AFBC, ...)

    // Усе, що шар прийняв би. Рендерер може обрати дешевший варіант:
    // напр. RGB565 замість XRGB8888 вдвічі зменшує запис у пам'ять, що
    // на чіпах з вузькою шиною (RK3566) відчутно.
    std::vector<uint32_t> supported_formats;

    ColorSpace colorspace = ColorSpace::Unknown;
    ColorRange color_range = ColorRange::Unknown;

    // Що бекенд реально віддає в кабель. Глибину буфера тут не дублюємо —
    // її вже однозначно задає fourcc (XRGB8888 -> 8 біт на канал).
    ColorFormat color_format = ColorFormat::Unknown;

    double refresh_hz() const { return refresh_mhz / 1000.0; }

    // Бюджет на всю обробку одного кадру. Усе, що не вклалося, поїде на
    // наступну розгортку.
    int64_t frame_time_ns() const {
        return refresh_mhz > 0 ? (1000000000LL * 1000LL) / refresh_mhz : 0;
    }

    bool valid() const { return width > 0 && height > 0; }
    Rect bounds() const { return Rect{0, 0, width, height}; }

    bool supports(uint32_t f) const {
        for (uint32_t s : supported_formats) {
            if (s == f) return true;
        }
        return false;
    }
};

// ---------------------------------------------------------------------
// Кадр
// ---------------------------------------------------------------------

// Кадр як dmabuf — те, що вміють обидва бекенди без копіювання пікселів:
// KMS зробить із нього DRM framebuffer, GL — EGLImage.
struct Frame {
    static constexpr int kMaxPlanes = 4;

    uint32_t fourcc = 0;
    uint64_t modifier = 0;
    int width = 0;
    int height = 0;

    int n_planes = 0;           // площин формату: NV12 -> 2, ARGB -> 1
    int fd[kMaxPlanes] = {-1, -1, -1, -1};
    uint32_t stride[kMaxPlanes] = {};
    uint32_t offset[kMaxPlanes] = {};

    // Видима частина. Апаратні декодери віддають буфер, вирівняний до
    // макроблоків (1080 лежить у 1088), показувати треба лише crop.
    // Порожній crop == весь кадр.
    Rect crop{};

    // Тримає власника пам'яті живим, доки бекенд кадром користується.
    //
    // ЧОМУ ЦЕ ПОТРІБНО НАВІТЬ У GL. EGL справді сам стежить за часом
    // життя EGLImage — але лише всередині GL. Про буфер, з якого той
    // EGLImage зроблено, він не знає нічого: dmabuf прийшов ззовні, від
    // декодера, і повернути слот у пул декодера має той, хто цей слот
    // брав. Імпорт dmabuf не передає володіння.
    //
    // Різниця між бекендами не в тому, ЧИ тримати, а ДОКИ:
    //   - пряме сканування (KMS): буфер читається весь час, поки кадр на
    //     екрані, тож тримати треба до підтвердження НАСТУПНОГО flip'а;
    //   - композиція (GL): джерело читається лише під час проходу
    //     зведення (~1 мс), тож відпустити можна щойно спрацює fence —
    //     ще ДО того, як кадр з'явиться на екрані.
    // Тобто GL справді послаблює тиск на пул декодера, але не скасовує
    // потребу керувати часом життя.
    std::shared_ptr<void> keepalive;

    bool valid() const {
        return width > 0 && height > 0 && n_planes > 0 && fd[0] >= 0;
    }
    Rect visible() const {
        return crop.empty() ? Rect{0, 0, width, height} : crop;
    }
};

// ---------------------------------------------------------------------
// Шар
// ---------------------------------------------------------------------

// Єдиний шар виводу. Отримується з DisplayManager::layer() і живе рівно
// стільки, скільки сам DisplayManager.
class Layer {
public:
    virtual ~Layer() = default;

    Layer(const Layer&) = delete;
    Layer& operator=(const Layer&) = delete;

    // Що цей шар уміє показати: розмір, частота, формат, колір.
    virtual const LayerInfo& info() const = 0;

    // Кладе кадр як наступний до показу. НЕ показує — показ робить
    // DisplayManager::present(). Розділено тому, що в KMS це дві різні
    // операції (підготувати стан і зробити atomic commit), і зливати їх
    // означало б ховати реальну поведінку заліза.
    //
    // Класти можна частіше, ніж показувати: переможе останній кадр,
    // решта порахується у dropped.
    virtual bool submit(const Frame& frame) = 0;

protected:
    Layer() = default;
};

// ---------------------------------------------------------------------
// Дисплей
// ---------------------------------------------------------------------

struct PresentStats {
    uint64_t presented = 0;       // кадрів реально показано
    uint64_t dropped = 0;         // витіснено новішими до показу
    // Час останнього показу — мітка ЯДРА, момент самої розгортки.
    // CLOCK_MONOTONIC, той самий годинник, що й у джерел.
    int64_t last_present_ns = 0;

    // ФАКТИЧНА частота розгортки: лічильник vblank'ів, поділений на час
    // між ними, на вікні від 1 до 30 с. Відрізняється від заявленої в
    // режимі, бо PLL округлює клок як може, а кварц ще й пливе від
    // нагріву. Саме її камера бере за опорну, підстроюючи свою.
    //
    // Точність — краще за 0.0005 Гц після першої секунди, тобто навмисно
    // тонше за крок підстроювання камери (1 мГц): контролер не має
    // ганятися за власним шумом вимірювання.
    // Нуль означає "ще не виміряно".
    double measured_hz = 0;
};

class DisplayManager {
public:
    virtual ~DisplayManager() = default;

    DisplayManager(const DisplayManager&) = delete;
    DisplayManager& operator=(const DisplayManager&) = delete;

    virtual bool open() = 0;
    virtual void close() = 0;
    virtual bool is_open() const = 0;

    // Єдиний шар виводу. Дійсний лише поки is_open().
    virtual Layer& layer() = 0;

    // Показує останній покладений кадр. Не блокує до розгортки: коли
    // кадр фізично потрапив на екран, спрацює present-колбек.
    virtual bool present() = 0;

    // Викликається з внутрішнього потоку бекенда після показу. Саме тут
    // відпускаються keepalive попередніх кадрів, тож нічого довгого в
    // ньому робити не можна.
    using PresentCallback = std::function<void(int64_t present_time_ns)>;
    virtual void set_present_callback(PresentCallback cb) = 0;

    virtual PresentStats stats() const = 0;

    // Для логів: "HDMI-A-1" тощо.
    virtual const std::string& description() const = 0;

protected:
    DisplayManager() = default;
};

} // namespace vrx::display
