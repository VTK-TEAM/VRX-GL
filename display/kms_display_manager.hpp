#pragma once

// Реалізація DisplayManager поверх DRM/KMS atomic.
//
// Задача класу рівно одна: перекидати буфери на екран у правильні моменти
// і чесно тримати їхні стани. Він нічого не малює й нічого не зводить —
// готовий кадр приходить ззовні.
//
// Три стани кадру, які тут відстежуються:
//   pending   — покладений через submit(), ще не відданий залізу;
//   in_flight — commit зроблено, підтвердження flip'а ще не прийшло;
//   current   — фізично на екрані, контролер читає саме його.
//
// Правильне звільнення буферів тримається на цьому поділі: буфер вільний
// не після commit'а, а лише коли flip підтверджено і він перестав бути
// current. Помилка тут дає розриви кадру, які потім довго не зрозуміти.
//
// Заголовок свідомо не тягне <xf86drmMode.h> і <gbm.h> — уся ця машинерія
// схована в .cpp, щоб не текти в кожен файл, що включає дисплей.

#include "display_manager.hpp"

#include <memory>
#include <string>

namespace vrx::display {

class KmsDisplayManager final : public DisplayManager {
public:
    struct Config {
        // Пристрій. card0 майже завжди, але на платах із кількома DRM
        // (напр. окремий VOP і NPU) буває інакше.
        std::string card = "/dev/dri/card0";

        // Режим беремо той, що дисплей позначив PREFERRED. Якщо тут
        // задати ненульові значення — спробуємо знайти саме такий режим,
        // а не знайшовши, все одно візьмемо PREFERRED і скажемо про це.
        int want_width = 0;
        int want_height = 0;
        int want_refresh_mhz = 0;

        // Пінимо явно, а не лишаємо драйверу.
        //
        // 8 біт: 10-бітних даних у тракті немає взагалі (H.265 8 біт,
        // OSD 8 біт, буфер XRGB8888), тож 30bit гнав би доповнені нулями
        // 8 біт і вимагав у 1.25 раза ширшого лінка. На наземній станції
        // з довгим кабелем це рівно та різниця, через яку картинка
        // починає моргати. Виграшу нуль.
        //
        // RGB: буфер у нас RGB, і віддавати його як YCbCr означає дві
        // конверсії замість жодної. Драйвер за замовчуванням обирає за
        // EDID — тобто на іншому моніторі поведінка інша.
        int color_depth_bits = 8;
        ColorFormat color_format = ColorFormat::RGB;

        // Забрати DRM master. Потрібне для зміни режиму й ексклюзивне:
        // якщо його тримає інший процес (lightdm, друга копія), відкриття
        // провалиться з поясненням у лозі.
        bool become_master = true;

        // GENLOCK: підігнати частоту розгортки під частоту джерела.
        //
        // Навіщо. Камера шле стабільно 60.00, панель показує 59.789 —
        // різниця 0.211 Гц. Фаза приходу кадру через це вільно пливе по
        // всьому періоду (повний оберт ~4.7 с), і раз на оберт кадр
        // неминуче або дублюється, або гине. Жодне підстроювання моменту
        // опиту цього не обходить: це арифметика, а не реалізація.
        //
        // Прибравши різницю частот, фазу можна тримати сталою — і тоді
        // достатньо зсуву в кілька мс, щоб поглинути джиттер мережі.
        //
        // Робиться зміною піксельного клока в таймінгах режиму:
        //     clock = hz * htotal * vtotal
        // Для 1366x768 це +0.35% — у межах можливостей PHY. PLL округлить
        // по-своєму, тому реальна частота міряється по мітках flip'а й
        // видається в PresentStats::measured_hz.
        //
        // 0 — не чіпати режим.
        double genlock_hz = 0.0;

    };

    // Два конструктори замість одного з типовим аргументом: усередині
    // оголошення класу Config ще неповний, і GCC на "= {}" спотикається.
    KmsDisplayManager();
    explicit KmsDisplayManager(Config cfg);
    ~KmsDisplayManager() override;

    bool open() override;
    void close() override;
    bool is_open() const override;

    Layer& layer() override;

    bool present() override;
    void set_present_callback(PresentCallback cb) override;

    PresentStats stats() const override;
    const std::string& description() const override;

    // Змінити піксельний клок на ходу, кГц.
    //
    // ПЕРЕВІРЕНО НА ЗАЛІЗІ: працює й реально керує фазою (148500 ->
    // 148900 кГц зсуває фазу на ~2.5 мс/с), АЛЕ ЕКРАН ГАСНЕ. Трасування
    // показало чому: шлях іде через disable_outputs -> atomic_enable ->
    // cru_set_rate, тобто повний modeset із вимкненням CRTC.
    //
    // Лишено як робочий актуатор на випадок, якщо колись знадобиться
    // разове вирівнювання ще до появи картинки. Для керування фазою в
    // роботі НЕ придатне.
    bool set_pixel_clock(uint32_t khz);
    uint32_t pixel_clock() const;

    // Довільна властивість CRTC за іменем, звичайним atomic-комітом БЕЗ
    // ALLOW_MODESET.
    //
    // РЕЗУЛЬТАТ ДОСЛІДЖЕННЯ (двома моніторами, з ftrace):
    //
    // Зміна ЛИШЕ "variable refresh rate" справді йде безшовно — у ядрі
    // викликається rockchip_connector_update_vfp_for_vrr з atomic_begin,
    // БЕЗ disable_outputs, і частота реально міняється (60.0 <-> 59.0).
    // Тобто драйвер тут ні в чому не винен.
    //
    // АЛЕ ЕКРАН УСЕ ОДНО БЛИМАЄ, і на обох перевірених моніторах. Крок
    // властивості цілочисельний, тобто мінімальна зміна це 1 Гц з 60 —
    // 1.7%. Приймач сприймає такий стрибок таймінгу як НОВИЙ СИГНАЛ і
    // перезахоплює синхронізацію. Дрібнішого кроку властивість не має.
    //
    // Якщо чіпати ще й "min/max refresh rate" або VRR_ENABLED — драйвер
    // додатково йде через повний modeset (disable_outputs + cru_set_rate).
    //
    // ВИСНОВОК: керувати фазою з боку дисплея не вийде. Актуатор має
    // бути на боці камери — зсув захоплення на N мс, без жодного ризику
    // для тракту показу.
    bool set_crtc_property(const char* name, uint64_t value);
    bool has_crtc_property(const char* name) const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::display
