#pragma once

// Оверлей: те, що малюється ПОВЕРХ відео власними текстурами.
//
// Той самий контракт, що й у FrameSource, і з тих самих причин: власний
// потік, реєстрація в рендерері, питає рендерер. Різниця одна — джерело
// віддає ОДИН кадр із декодера, а оверлей віддає СПИСОК КВАДІВ, бо OSD
// це двісті дрібних прямокутників із спільного атласу, а не картинка.
//
// ЧОМУ КВАДИ, А НЕ ГОТОВИЙ БУФЕР. Напрошується простіше: хай оверлей
// малює себе в ARGB-буфер, а рендерер вантажить його текстурою. Саме так
// зроблено в старому VRX, де OSD жив окремим DRM-плейном. Але тут це
// коштувало б повного завантаження екрана в GPU щоразу, коли змінилась
// хоч одна цифра телеметрії: 1366x768x4 = 4.2 МБ, і при 20 оновленнях на
// секунду це 84 МБ/с трафіку пам'яті. На RK3566 з одноканальним LPDDR4
// саме смуга пам'яті — головна стаття витрат, і платити її за перемальовку
// цифр безглуздо. Двісті квадів натомість це 19 КБ вершин.
//
// ЧОМУ ПІКСЕЛІ ТЕКСТУР ВІДДАЮТЬСЯ ОКРЕМО. Контекст GL належить потоку
// рендерера, і викликати glTexImage2D з чужого потоку не можна. Тому
// оверлей декодує PNG у себе (це разова робота при init) і віддає сирі
// пікселі; рендерер вантажить їх у GPU один раз і далі лише малює.

#include <cstdint>
#include <string>
#include <vector>

namespace vrx::render {

// Одна текстура оверлея: атлас гліфів або окрема картинка (бар, горизонт).
struct OverlayImage {
    // Стабільний ключ, за яким рендерер кешує завантажену текстуру.
    // Для картинок із диска це шлях до файлу.
    std::string id;
    int width = 0, height = 0;
    std::vector<uint8_t> rgba;   // RGBA8, тісно упаковано, перший рядок — верхній
};

// Один прямокутник. Чотири кути ЯВНО, а не x/y/w/h — бо горизонт
// обертається, і повернутий прямокутник осями не описується. Заразом це
// прибирає обертання з рендерера: він лишається дурним і просто малює
// те, що йому дали.
//
// Порядок вершин: лівий верхній, правий верхній, лівий нижній, правий
// нижній. Саме такий чекає збірка трикутників у батчері.
struct OverlayQuad {
    int image = 0;        // індекс у таблиці images()
    float x[4], y[4];     // частки екрана 0..1, початок у лівому ВЕРХНЬОМУ куті
    float u[4], v[4];     // 0..1 у текстурі; v=0 — ВЕРХНІЙ рядок картинки
};

// Знімок на один кадр. Будує потік оверлея, читає потік рендерера.
struct DrawList {
    std::vector<OverlayQuad> quads;

    // Зростає на кожен новий знімок. Рендерер за ним бачить, чи є сенс
    // перезбирати вершинний буфер, чи можна малювати попередній.
    uint64_t serial = 0;
};

class Overlay {
public:
    Overlay() = default;
    virtual ~Overlay() = default;

    Overlay(const Overlay&) = delete;
    Overlay& operator=(const Overlay&) = delete;

    virtual const char* name() const = 0;

    // Піднімає й зупиняє ВЛАСНІ потоки оверлея.
    virtual bool start() = 0;
    virtual void stop() = 0;

    // Геометрія кадру. Каже рендерер при реєстрації і при її зміні —
    // саме тому main не має про неї знати й не мусить нічого передавати.
    //
    // Потрібна оверлею, бо розміри гліфів в атласі задані в ПІКСЕЛЯХ
    // (нормалізованих на розмір атласа), а квади віддаються в частках
    // екрана. Без цього не перевести одне в інше.
    // РОЛЬ ЕКРАНА тут навмисно: з двома екранами оверлей малюється двічі,
    // і геометрія в них різна. Той самий гліф у частках екрана мусить
    // рахуватись від СВОЄЇ висоти, інакше на другому екрані він поїде.
    virtual void set_frame_size(int role, int width, int height) = 0;

    // Текстури. Викликається рендерером із свого потоку один раз після
    // реєстрації — до цього моменту оверлей уже має бути ініціалізований.
    virtual const std::vector<OverlayImage>& images() const = 0;

    // Щокадру, з потоку рендерера. НЕ МАЄ ПРАВА БЛОКУВАТИ — тут очікування
    // означає пропущений vblank.
    //
    // Повертає false, якщо нового знімка немає; тоді рендерер малює
    // попередній. Це не помилка, а норма: OSD оновлюється разів у двадцять
    // на секунду, а показ іде шістдесят.
    // РОЛЬ каже, для ЯКОГО екрана зараз потрібен знімок. Вміст різний:
    // курсор малюється лише там, де він фізично зараз, кнопка OSD показує
    // стан саме цього екрана, а рамка виділення — його розкладку.
    //
    // Кешувати знімок оверлей мусить окремо на кожну роль: рендерер
    // питає їх по черзі в межах одного кадру.
    virtual bool acquire(int role, DrawList& out) = 0;
};

} // namespace vrx::render
