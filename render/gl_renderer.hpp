#pragma once

// Рендерер: зводить шари на GPU у власний буфер і сам віддає його на екран.
//
// Працює у ВЛАСНОМУ потоці й керує собою сам. Ззовні — лише три виклики:
// init(), start(), stop(). Жодного "намалюй кадр" чи "покажи" з боку
// викликача немає й не буде: темп задає звільнення буферів, а про нього
// знає лише сам рендерер.
//
// Хто чим володіє:
//   - цільові буфери належать ДИСПЛЕЮ: він знає вимоги до сканування і
//     він же єдиний знає, який із них зараз читає сканер;
//   - рендерер тримає лише GL-обгортки над ними (EGLImage + FBO), бо їх
//     можна створити тільки в потоці з поточним контекстом. Це кеш, а не
//     джерело правди.
//
// Темп циклу задає звільнення буфера. Рендерер підписується на
// підтвердження flip'а і прокидається саме на нього — без опитування й
// без сну "на око".

#include "../display/display.hpp"
#include "../source/frame_source.hpp"
#include "overlay.hpp"
#include "scene.hpp"

#include <cstdint>
#include <memory>
#include <string>

namespace vrx::render {

struct RenderStats {
    uint64_t frames = 0;        // намальовано й віддано на показ
    uint64_t stalls = 0;        // цикл чекав вільного буфера
    double last_draw_ms = 0;    // тривалість проходу GPU (по fence)
    double avg_draw_ms = 0;

    // Наскрізна затримка: від виходу кадру з декодера до підтвердження
    // показу. Головна метрика тракту для FPV.
    double latency_avg_ms = 0;
    double latency_max_ms = 0;

    // Поточний зсув опиту від початку періоду — видно, як фаза пливе.
    double poll_offset_ms = 0;

    // ФАЗА: де в періоді розгортки опиняється прихід кадру з камери.
    // 0 — кадр приходить рівно на vblank (найгірше: показ аж через
    // період). Ближче до poll_offset — найкраще: показ одразу.
    // Затримка від приходу до показу = період - фаза.
    double phase_ms = 0;
    double phase_drift_ms_per_s = 0;

    // Розкид приходу кадрів навколо phase_ms, оцінка сигми. Задає, на
    // яку відстань від точки опиту треба вести фазу: підійти ближче
    // означає ловити виплески джитера, відійти далі — платити
    // затримкою ні за що. 0 = вибірка ще закоротка.
    double phase_jitter_ms = 0;

    // ЧОГО ВАРТЕ САМЕ ЧИСЛО phase_ms: σ середнього по вікну виміру
    // (розкид / √кадрів у вікні). Потрібне тому, хто ставить пороги на
    // фазу — інакше поріг задається наосліп і може виявитись дрібнішим
    // за невизначеність величини, з якою його порівнюють. 0 = ще нема.
    double phase_noise_ms = 0;

    // КАДРИ, ЩО ЗАПІЗНИЛИСЬ НА ОПИТ: прийшли після точки опиту, тому
    // поїдуть на екран на розгортку пізніше. Не втрачені й не повторені —
    // просто з зайвим періодом затримки, і жоден інший лічильник цього не
    // показує. Це пряма міра роботи петлі фази: вона й існує, щоб тримати
    // прихід кадру ПЕРЕД цією точкою.
    uint64_t taken_new = 0;     // нових кадрів усього (знаменник)
    uint64_t late = 0;          // з них спізнилися

    // КРОК ЗЙОМКИ між сусідніми ПОКАЗАНИМИ кадрами. Показ іде рівно по
    // сітці розгортки, тож плавність руху задає саме він. Ідеал — усе в
    // step_ok. Будь-що в repeat/gap означає ривок, якого лічильники
    // повторів і пропусків НЕ БАЧАТЬ: з їхнього боку ми чесно взяли по
    // кадру на розгортку.
    uint64_t step_repeat = 0;   // той самий кадр удруге
    uint64_t step_short = 0;    // менше пів періоду
    uint64_t step_ok = 0;       // один період +-50%
    uint64_t step_gap = 0;      // півтора періоду й більше
    double step_min_ms = 0;
    double step_max_ms = 0;
};

class GlRenderer {
public:
    struct Config {
        // Кільце буферів. Два — мінімум і оптимум за затримкою: у той,
        // що зараз сканується, малювати не можна. Третій додав би
        // стійкості до джитера ціною кадру затримки.
        int buffers = 2;

        // Замість зведення малювати три смуги R/G/B — перевірка порядку
        // каналів. Ганяти першою на кожній новій платі: помилка тут
        // зіпсує колір усього відео, а на службовій графіці її не видно.
        bool colortest = false;

    };

    GlRenderer();
    ~GlRenderer();

    GlRenderer(const GlRenderer&) = delete;
    GlRenderer& operator=(const GlRenderer&) = delete;

    // Готує GBM і EGL, перевіряє наявність потрібних розширень. Розмір і
    // формат буферів беруться з display.info() — тобто дисплей
    // має бути вже відкритий.
    //
    // GL-об'єкти тут НЕ створюються: контекст робиться поточним у
    // робочому потоці, а без нього створювати нічого не можна.
    //
    // Дві перевантаження замість типового аргументу: усередині
    // оголошення класу Config ще неповний, і GCC на "= Config{}"
    // спотикається (те саме в KmsDisplayManager).
    bool init(display::Display& display);
    bool init(display::Display& display, Config cfg);

    // Запускає робочий потік. З цього моменту картинка йде на екран.
    bool start();

    // Зупиняє потік і чекає його завершення. Безпечно викликати двічі.
    void stop();

    bool is_running() const;
    RenderStats stats() const;

    // Реєстрація джерел. Можна в будь-який момент, зокрема на ходу:
    // рендерер бере зріз списку на кожен кадр.
    //
    // Рендерер НЕ володіє життям джерела і не запускає його — за це
    // відповідає той, хто джерело створив. Тут лише shared_ptr, щоб
    // джерело не зникло посеред кадру.
    // СЦЕНА — де саме малювати кожне джерело, окремо на кожен екран.
    // Рендерер її лише читає; пишуть у неї налаштування за замовчуванням
    // (при старті) і редактор розкладки (мишею).
    Scene& scene();

    void add_source(std::shared_ptr<source::FrameSource> src);
    void remove_source(const std::shared_ptr<source::FrameSource>& src);
    int source_count() const;

    // Оверлей малюється ПОВЕРХ джерел, зі змішуванням. Реєстрація така
    // сама, як у джерела: рендерер не володіє його життям і не запускає
    // його — лише питає квади щокадру.
    //
    // Геометрію кадру рендерер повідомляє сам, тут же при реєстрації:
    // оверлею вона потрібна, щоб перевести піксельні розміри гліфів у
    // частки екрана, а зовнішній код не має про це думати.
    void add_overlay(std::shared_ptr<Overlay> ovl);

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace vrx::render
